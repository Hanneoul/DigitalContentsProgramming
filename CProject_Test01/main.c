#include <stdio.h>

/*
================================================================================
 [초보자를 위한 ANSI 3비트 컬러 & 검정색의 비밀]
================================================================================

 1. ANSI 3비트(표준 8색)에 검정색이 없나요?
 -------------------------------------------------------------------------
 - 아님. 검정색은 분명히 존재함. 번호로는 **0번**임.
 - 글자색(Foreground)은 `\033[30m`, 배경색(Background)은 `\033[40m`이 검정색임.

 2. 왜 검정색이 안 보일까? (또는 회색으로 보일까?)
 -------------------------------------------------------------------------
 - [배경과의 충돌]: 대부분의 터미널 기본 배경색이 이미 검정색임. 그래서 검정색 픽셀을
   찍어도 아무것도 안 그린 것처럼 보일 수 있음.
 - [터미널 테마 문제]: 일부 현대적인 터미널(VS Code 터미널, 윈도우 터미널 등)은
   '완전한 검정(#000000)' 대신 시력 보호를 위해 '어두운 회색'을 0번 검정으로 매핑함.
 - [해결책]: 정말 진한 검정을 원한다면 우리가 앞서 배운 **24비트 트루 컬러**
   (`\033[48;2;0;0;0m`)를 사용하는 것이 가장 확실함.

 3. 월드 좌표계와 화면 좌표계 (스크롤 시스템)
 -------------------------------------------------------------------------
 - [월드 좌표]: 게임 속 절대 위치 (예: 0 ~ 1000)[cite: 1].
 - [화면 좌표]: 우리 눈에 보이는 터미널 창 안의 위치 (예: 0 ~ 39)[cite: 1].
 - [스크롤 공식]: 화면 좌표 = 월드 좌표 - 카메라 위치[cite: 1].
   카메라가 오른쪽으로 가면 모든 물체가 왼쪽으로 밀려나는(스크롤되는) 이유임.

================================================================================
*/

#define SCR_W 40
#define SCR_H 20
#define WORLD_W 200

// [함수] 화면 좌표계에 24비트 트루 컬러로 점 찍기
void draw_pixel(int x, int y, int r, int g, int b) {
    if (x < 0 || x >= SCR_W || y < 0 || y >= SCR_H) return;
    // 커서 이동 후 배경색 지정 출력[cite: 1]
    printf("\033[%d;%dH\033[48;2;%d;%d;%dm  \033[0m", y + 1, (x * 2) + 1, r, g, b);
}

int main() {
    int playerX = 10;
    int cameraX = 0;
    char cmd;

    // 초기 세팅: 화면 지우기, 커서 숨기기[cite: 1]
    printf("\033[2J\033[?25l");

    while (1) {
        // 1. 카메라 위치 계산 (플레이어를 화면 중앙에 유지)
        cameraX = playerX - (SCR_W / 2);
        if (cameraX < 0) cameraX = 0;
        if (cameraX > WORLD_W - SCR_W) cameraX = WORLD_W - SCR_W;

        // 2. 렌더링 (그리기)
        // 화면 전체를 짙은 파란색으로 일단 채움 (하늘)
        for (int y = 0; y < SCR_H; y++) {
            for (int x = 0; x < SCR_W; x++) {
                draw_pixel(x, y, 10, 10, 40);
            }
        }

        // 월드 지형물 그리기 (10칸 간격으로 검정색 기둥 배치)
        // 3비트 0번 검정이 불안정할 수 있으니 24비트 (0,0,0)으로 확실하게 그림
        for (int wx = 0; wx < WORLD_W; wx += 10) {
            int sx = wx - cameraX; // 월드 좌표를 화면 좌표로 변환[cite: 1]
            if (sx >= 0 && sx < SCR_W) {
                for (int sy = 5; sy < SCR_H-5; sy++) {
                    draw_pixel(sx, sy, 80, 80, 80); // "진짜" 검정색 픽셀
                }
            }
        }

        // 플레이어 캐릭터 (노란색)
        draw_pixel(playerX - cameraX, SCR_H / 2, 255, 255, 0);

        // UI 출력
        printf("\033[%d;1H", SCR_H + 2);
        printf(" [World X: %3d] (a:좌, d:우, q:종료) ", playerX);

        // 3. 입력 및 로직
        cmd = getch();
        if (cmd == 'a' && playerX > 0) playerX--;
        if (cmd == 'd' && playerX < WORLD_W - 1) playerX++;
        if (cmd == 'q') break;

        // 화면 갱신을 위해 지우기 (성능을 위해 위치를 직접 덮어쓰는 게 좋으나 여기선 간단히)
        printf("\033[2J");
    }

    printf("\033[?25h\033[2J");
    return 0;
}