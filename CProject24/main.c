/*
 * =========================================================================
 * [강의 자료: scanf의 스캔 셋(Scan Set)과 입출력 메커니즘]
 * =========================================================================
 * 1. scanf("%[^\n]s", input)의 정밀 분석:
 *    - %[] (Scan Set): 특정 문자 집합을 정의하여 입력 패턴을 제어함.
 *    - ^ (Caret/Not): 대괄호 안의 첫 번째 문자로 쓰일 때 "제외(Exclusion)"를 의미.
 *    - \n (Newline): 엔터 키를 의미함.
 *    - 동작 원리:
 *      기존 %s는 공백(Space)을 만나면 멈추지만, %[^\n]은 '엔터'가 나오기
 *      전까지 만나는 모든 문자(공백 포함)를 하나의 바구니(배열)에 담음.
 *      즉, "엔터가 나오기 전까지는 멈추지 마라"는 특수 필터임.
 *
 * 2. printf("%s", input)의 동작 방식:
 *    - %s 서식 지정자는 인자로 받은 '주소'부터 시작해서 읽기 시작함.
 *    - 메모리를 한 칸씩 이동하며 읽다가 '\0' (NULL 문자)를 만나는 순간
 *      출력을 중단함. (데이터의 시작 주소만 알면 끝까지 찾아가는 방식)
 *
 * 3. 메모리 안전성 (Buffer):
 *    - char input[128] = { 0 }; 처럼 배열을 미리 0으로 초기화하는 습관은
 *      문자열의 끝을 보장하고 쓰레기 값 출력을 방지하는 아주 좋은 습관임.
 * =========================================================================
 */

#define _CRT_SECURE_NO_WARNINGS // 최신 Visual Studio에서 보안 경고를 무시함
#include <stdio.h>

int main()
{
    // 128바이트 크기의 문자 방을 만들고 모두 0(NULL)으로 초기화함
    char input[128] = { 0 };

    printf("입력> ");

    /*
     * [스캔 셋 필터 적용]
     * - %[^\n] : 엔터(\n)가 아닌(^) 모든 문자를 읽어들임.
     * - 이 방식을 통해 "Hello World" 처럼 중간에 공백이 있는 문장도
     *   한 번에 입력받을 수 있음. (표준 %s였다면 "Hello"에서 잘림)
     */
    scanf("%[^\n]s", input);

    /*
     * [출력]
     * - 저장된 배열의 시작 주소부터 NULL 문자가 나올 때까지 화면에 뿌림.
     */
    printf("출력> %s\n", input);

    return 0;
}