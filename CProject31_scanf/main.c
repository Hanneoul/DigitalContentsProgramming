/**
 * =================================================================
 * [C언어 강의 핵심교안]
 * 입출력 함수 - scanf()의 모든 것과 초고급 예외 처리 기법
 * 
 * 1. scanf()의 어원과 정의
 *   - scanf는 "Scan Formatted"의 약어임. 직역하면 "형식화된 입력 스캔기".
 *   - 역할: 사용자가 키보드로 입력한 문자열 상태의 데이터를 프로그램이 
 *          연산할 수 있는 실제 데이터 형태(정수, 실수, 문자 등)로 변환 및 조립함.
 *   - 목적: 프로그램이 정적 데이터(예: int a = 10;)에만 의존하지 않고, 
 *          사용자의 입력에 따라 동적으로 반응하는 인터랙티브 환경을 구축하기 위함.
 * 
 * 2. 표준 콘솔 입력 함수의 비교 및 특징
 *   - 입력 요구사항에 따라 적절한 함수를 선택해야 메모리 오염과 오작동을 막을 수 있음.
 * 
 *     ① scanf()
 *        - 특징: 데이터의 '타입(형식)'을 서식 지정자로 지정하여 파싱함.
 *        - 구분자: 공백(스페이스), 탭(\t), 개행(엔터, \n)을 기준으로 데이터를 쪼갬.
 *        - 용도: 공백이 없는 데이터 포맷 파싱, 연속된 숫자나 변수를 입력받을 때 적합.
 * 
 *     ② getchar() / _getch()
 *        - getchar(): 표준 버퍼형 문자 입력 함수. 엔터를 누를 때까지 입력 버퍼에 
 *                     데이터를 대기시켰다가 딱 1바이트(문자 1개)만 가져옴. 
 *                     입력한 문자가 화면에 표시됨(Echo). 
 *                     주로 버퍼에 남은 잔여 데이터(\n 등)를 소거하는 청소용으로 자주 활용됨.
 *        - _getch(): 비표준 실시간 입력 함수. (<conio.h> 라이브러리 필요)
 *                    입력 버퍼를 거치지 않고 키보드를 누르는 순간 즉시 값을 프로그램에 전달함.
 *                    입력한 문자가 화면에 표시되지 않음(No-Echo).
 *                    용도: 실시간 키 입력을 처리하는 콘솔 게임 구동, 비밀번호 가림 입력 등.
 * 
 *     ③ fgets()
 *        - 특징: '한 줄(Line)' 전체를 통째로 읽어오는 표준 함수. 
 *        - 안정성: 기존 gets() 함수는 입력 크기 제한이 없어 버퍼 오버플로우 보안 취약점이 
 *                  존재했기에 표준에서 퇴출됨. 대신 크기 제한이 가능한 fgets()를 사용해야 함.
 *        - 용도: 띄어쓰기가 포함된 문장, 공백이 포함된 긴 텍스트 입력 처리 시 필수적임.
 * 
 * 3. 하드웨어와 소프트웨어의 가교: 주소 연산자(&)와 입력 버퍼(Standard Input Buffer)
 *   - `&` (주소 연산자)
 *     : 변수명만 지정하면 컴파일러는 값을 저장할 대상을 찾지 못함. 
 *       메모리 공간에서 해당 변수가 할당받은 '실제 번지수(주소)'를 가리켜야 데이터 배달이 가능함.
 *       그 식별자 역할을 하는 기호가 &임.
 *       (단, 문자열을 저장하는 배열 이름은 그 자체로 주소 상수를 의미하므로 &를 붙이지 않음)
 *   - 입력 버퍼 (stdin)
 *     : 키보드로 타이핑한 값은 OS 내부의 임시 대기실인 '입력 버퍼'에 순차적으로 기록됨.
 *       scanf는 이 버퍼를 탐색하며 지정된 형식 지정자 규칙에 맞게 데이터를 소모함.
 *       파싱 과정에서 소비되지 않고 남은 개행 문자(\n)나 비정상 입력값은 버퍼에 그대로 
 *       잔류하며, 이는 후속 입력 함수의 오작동을 유발하는 원인이 됨.
 * 
 * 4. 서식 지정자(% 키워드) 가이드 및 고급 제어 기술
 * 
 *    [표준 형식 지정자 요약]
 *    +--------+------------------+--------------------------------------------+
 *    | 지정자 | 대상 자료형       | 입출력 메커니즘 상의 주의 포인트           |
 *    +--------+------------------+--------------------------------------------+
 *    |  %d    | int (정수)        | 선행 공백과 엔터를 자동으로 건너뛰고 숫자만 파싱. |
 *    |  %f    | float (실수)      | 단정밀도 실수 입력.                        |
 *    |  %lf   | double (실수)     | printf와 달리 scanf에서는 반드시 %lf를 사용해야 함. |
 *    |  %c    | char (문자)       | 버퍼의 선행 공백, 스페이스, 엔터(\n)까지 문자로 |
 *    |        |                  | 인식하여 소모하므로 전처리(공백 삽입)가 필수적임. |
 *    |  %s    | char[] (문자열)   | 공백이나 엔터를 만나는 즉시 문자열의 끝으로 판단함. |
 *    +--------+------------------+--------------------------------------------+
 * 
 *    [고급 입력 제어 기술]
 *    - `%[숫자]d / %[숫자]s` : 정해진 바이트 크기만큼만 입력을 강제 제한하여 읽기 처리.
 *    - `%*d / %*c`         : 스트림 데이터를 읽어들이되, 변수에 저장하지 않고 소거(Filtering).
 *    - `%[스캔셋]`         : 대괄호 내부에 명시된 문자 집합만 유효한 입력으로 판정함.
 *    - `%[^스캔셋]`        : 해당 문자가 등장하기 전까지의 모든 텍스트를 스트림에서 추출함.
 *                            (치트키: %[^\n] -> 개행 문자가 나오기 전까지 공백 포함 전체 흡수)
 *    - `%i`                : 입력된 데이터의 접두사(0, 0x)를 인식하여 8진수/16진수를 10진수로 자동 변환.
 * 
 * 5. 입력 스트림의 종단 처리: EOF(End Of File)와 OS별 입력 단축키
 *   - 정의: EOF는 데이터 스트림의 끝을 나타내는 표준 상수 값(-1로 정의됨)임.
 *   - 활용: 데이터의 입력 횟수가 사전에 지정되지 않은 알고리즘이나 대용량 텍스트 파싱 시, 
 *          데이터 유입이 종료되었음을 알리는 신호로 사용됨.
 *   - 운영체제(OS)별 콘솔 종료 인터럽트 입력 단축키:
 *     ① Windows 환경
 *        - 단축키: `Ctrl + Z` 호출 후 `Enter` 입력
 *        - 동작: 스트림 상에 EOF 신호를 강제로 주입하여 scanf 인터러프트를 빠져나감.
 *     ② Linux / macOS 환경
 *        - 단축키: `Ctrl + D` 입력 (별도의 Enter 입력 불요)
 *        - 동작: 현재 입력 스트림을 즉시 플러시(Flush)하며 데이터가 없으면 EOF로 처리함.
 * 
 * =================================================================
 */

#include <stdio.h>

int main() {
    // -------------------------------------------------------------
    // [준비 단계: 변수 선언]
    // -------------------------------------------------------------
    int age, year, month, day;
    float weight;
    double height;
    char grade;
    char name[20];
    char full_text[100];
    int result;

    // [추가 심화 변수]
    char safe_buf[5];       // 버퍼 오버플로우 방지 테스트용 (실제 4글자 저장 가능)
    int auto_base;          // %i 진법 자동 감지 테스트용
    int loop_num;           // EOF 무한 입력 테스트용


    /*--------------------------------------------------------------
     * 1. 가장 기초적인 입력과 주소 연산자 (&)
     *--------------------------------------------------------------
     * [설명] age 변수가 살고 있는 '방 번호(주소)'를 가리키기 위해
     *        변수명 앞에 '&'(앰퍼샌드)를 붙여 배달 위치를 지정함.
     */
    printf("1. 나이를 입력하세요: ");
    scanf("%d", &age);


    /*--------------------------------------------------------------
     * 2. double형의 배신 (%f vs %lf)
     *--------------------------------------------------------------
     * [설명] 출력(printf)과 달리 입력(scanf)에서는 정밀도에 따른
     *        메모리 크기를 정확히 맞춰야 하므로 double은 반드시 %lf를 사용함.
     */
    printf("2. 키와 몸무게를 입력하세요 (예: 175.5 70.3): ");
    scanf("%lf %f", &height, &weight);


    /*--------------------------------------------------------------
     * 3. %c와 입력 버퍼(Buffer)의 비밀
     *--------------------------------------------------------------
     * [설명] 앞의 입력에서 남겨둔 '엔터(\n)'가 버퍼에 남아있다가
     *        %c로 그냥 들어가 버리는 버그를 막기 위해 서식 앞에 공백(" %c")을 둠.
     */
    printf("3. 학점을 입력하세요 (A, B, C...): ");
    scanf(" %c", &grade);


    /*--------------------------------------------------------------
     * 4. % 키워드 마술 ① : 특정 길이만큼만 잘라 읽기 (%[숫자]d)
     *--------------------------------------------------------------
     * [설명] 숫자가 하나로 길게 붙어있어도 지정한 글자 수만큼
     *        컴퓨터가 칼같이 쪼개서 읽어옴. (예: 20260522 -> 2026 / 05 / 22)
     */
    printf("4. 생년월일 8자리를 붙여서 입력해보세요 (예: 20260522): ");
    scanf("%4d%2d%2d", &year, &month, &day);


    /*--------------------------------------------------------------
     * 5. % 키워드 마술 ② : 읽기 거부와 데이터 필터링 (%*d)
     *--------------------------------------------------------------
     * [설명] 형식 지정자 사이에 별표(*)를 넣으면 "읽기는 하되 버려라"라는 뜻.
     *        구분자(하이픈 등) 사이에 있는 특정 데이터를 스킵할 때 유용함.
     */
    printf("5. 날짜를 하이픈을 넣어서 입력해보세요 (예: 2026-05-22): ");
    scanf("%d-%*d-%d", &year, &day);


    /*--------------------------------------------------------------
     * 6. %s의 한계와 주소 연산자 생략
     *--------------------------------------------------------------
     * [설명] 문자열 배열(name)은 그 이름 자체가 이미 메모리 주소이므로 &를 생략함.
     *        %s는 공백(스페이스)이나 엔터를 만나면 입력을 즉시 종료함.
     */
    printf("6. 이름을 공백 없이 입력하세요: ");
    scanf("%s", name);


    /*--------------------------------------------------------------
     * 7. % 키워드 마술 ③ : 스캔셋(Scanset)으로 공백 포함 문자열 읽기 (%[^...])
     *--------------------------------------------------------------
     * [설명] %[^문자] 서식은 해당 문자가 나오기 전까지의 모든 것을 다 읽음.
     *        %[^\n]은 엔터가 나오기 전까지 공백을 포함한 문장 전체를 통째로 흡수함.
     */
    printf("7. 오늘 하고 싶은 말을 공백 포함해서 입력하세요: ");
    scanf(" %[^\n]", full_text);


    /*--------------------------------------------------------------
     * 8. 심화 ① : 정밀한 문자열 방어막 - 버퍼 오버플로우 방지 (%[숫자]s)
     *--------------------------------------------------------------
     * [설명] 크기가 5인 배열에 대책 없이 긴 문자열을 넣으면 프로그램이 터짐.
     *        %4s 처럼 [배열크기-1] 개수를 지정하면 딱 4글자만 안전하게 읽고
     *        마지막 칸에 문자열의 끝을 알리는 널 문자('\0')를 자동으로 채워줌.
     */
    printf("8. 아무 글자나 길게 쳐보세요 (딱 4글자만 안전하게 잘라 읽음): ");
    scanf("%4s", safe_buf);


    /*--------------------------------------------------------------
     * 9. 심화 ② : 정수 입력의 카멜레온 - 진법 자동 감지 (%i)
     *--------------------------------------------------------------
     * [설명] %d는 무조건 10진수로만 읽지만, %i는 입력된 접두사를 보고 진법을 판단함.
     *        - 그냥 숫자(10) -> 10진수 10
     *        - 0으로 시작(010) -> 8진수 8
     *        - 0x로 시작(0x10) -> 16진수 16으로 자동 변환하여 정수형 변수에 저장함.
     */
    printf("9. 진법 감지 테스트 (예: 10 또는 010 또는 0x10 입력): ");
    scanf("%i", &auto_base);


    /*--------------------------------------------------------------
     * 10. 방어 코딩의 핵심: scanf의 리턴값과 버퍼 비우기
     *--------------------------------------------------------------
     * [설명] scanf는 성공적으로 읽어들인 데이터의 '개수'를 반환함.
     *        %d 숫자를 받아야 하는데 사용자가 문자(abc)를 치면 리턴값이 0이 됨.
     *        이때 버퍼에 남은 쓰레기(abc)를 치우지 않으면 무한 루프에 빠지므로
     *        while(getchar() != '\n')으로 강제 청소를 진행함.
     */
    printf("10. 숫자를 입력해보세요 (에러 유도를 위해 문자를 입력해보셈): ");
    result = scanf("%d", &age);

    if (result == 0) {
        printf(" -> [경고] 정수가 아닙니다! 버퍼를 청소합니다.\n");
        while (getchar() != '\n');
    }
    else {
        printf(" -> 성공적으로 값을 읽었습니다.\n");
    }


    /*--------------------------------------------------------------
     * 11. 심화 ③ : 언제 끝날지 모르는 입력 처리 - EOF(End Of File) 판단
     *--------------------------------------------------------------
     * [설명] 알고리즘 문제에서 "입력의 개수가 주어지지 않을 때" 사용하는 끝판왕 패턴.
     *        scanf는 입력이 끝나거나 콘솔 종료 신호(Windows: Ctrl+Z, 리눅스: Ctrl+D)가
     *        들어오면 EOF(-1)를 반환하므로, 이를 이용하여 loop를 안전하게 탈출함.
     */
    printf("11. [무한 입력 모드] 숫자를 계속 입력해보세요.\n");
    printf("    (종료하려면 숫자 입력 후 엔터를 치고, 아무것도 안 뜬 상태에서 Ctrl + Z 누른 뒤 엔터)\n");

    // 이전에 남은 입력 버퍼를 비워 정상적인 EOF 테스트 환경 확보
    while (getchar() != '\n');

    while (scanf("%d", &loop_num) != EOF) {
        printf("    => 대기실에서 읽어온 숫자: %d (다음 숫자 대기 중...)\n", loop_num);
    }
    printf(" -> [알림] EOF(종료 신호)가 감지되어 루프를 안전하게 탈출했습니다.\n");


    // -------------------------------------------------------------
    // [최종 결과 확인 결과 출력 창]
    // -------------------------------------------------------------
    printf("\n================ [입력 결과 최종 확인] ================\n");
    printf("나이: %d, 키: %.1f, 몸무게: %.1f, 학점: %c\n", age, height, weight, grade);
    printf("쪼개기 날짜: %d년 %d월 %d일\n", year, month, day);
    printf("이름: %s\n", name);
    printf("하고 싶은 말: %s\n", full_text);
    printf("안전 잘라내기 문자열(최대4글자): %s\n", safe_buf);
    printf("자동 진법 변환 결과(10진수 출력): %d\n", auto_base);
    printf("======================================================\n");

    return 0;
}