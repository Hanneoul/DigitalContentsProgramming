 /*
  * =========================================================================
  * [강의 자료: 배열, 포인터, 그리고 문자열(String)의 삼각관계]
  * =========================================================================
  * 1. 배열(Array)과 주소:
  *    - char name[10]; 은 문자 10개가 살 수 있는 연속된 방을 예약하는 것임.
  *    - 배열의 이름(name)은 사실 '첫 번째 방의 주소(&name[0])'와 같음.
  *
  * 2. 문자열(String)의 정체:
  *    - C언어에서 문자열은 char형 배열에 문자를 차곡차곡 채워 넣은 것임.
  *    - 가장 중요한 규칙: 문자열의 끝에는 반드시 '\0' (NULL 문자)이 붙음.
  *    - 컴퓨터는 주소만 보고 글자를 읽다가 '\0'을 만나는 순간 "아, 끝났구나" 함.
  *
  * 3. 포인터로 문자열 다루기:
  *    - char* p = "Hello"; 라고 쓰면, 메모리 어딘가에 저장된 "Hello"의
  *      '시작 주소'만 포인터 p가 들고 있는 것임.
  *
  * 4. 게임 대사 시스템의 원리:
  *    - printf("%s", 주소); 를 실행하면, 컴퓨터는 해당 '주소'부터 시작해서
  *      '\0'이 나올 때까지 모든 문자를 화면에 뿌림.
  * =========================================================================
  */

#include <stdio.h>

int main()
{
    // [1] 배열을 이용한 문자열 저장 (고정된 저장 공간)
    // "Warrior Gemini"는 12글자지만, 마지막 '\0'을 위해 최소 13칸이 필요함.
    char heroName[] = "Warrior Gemini";

    // [2] 포인터를 이용한 문자열 가리키기 (주소만 복사)
    // 대사 내용을 가리키는 포인터. 실제 문장 데이터는 메모리의 '상수 영역'에 있음.
    char* dialogue = "마왕, 이 세계의 평화는 내가 지킨다!";
    char* npcName = "마왕 발록";

    // [3] 주소와 사이즈 확인 (이전 시간에 배운 개념 복습)
    printf("[SYSTEM MEMORY INFO]\n");
    printf("- Hero Name Address : %p\n", (void*)heroName);
    printf("- Dialogue Address  : %p\n", (void*)dialogue);
    printf("- char* Size        : %d bytes (주소값의 크기)\n", sizeof(dialogue));
    printf("--------------------------------------------------\n\n");

    // [4] 게임 대사 출력 실습
    // %s는 "주소를 줄 테니 '\0'이 나올 때까지 읽어서 출력해라"는 뜻임.
    printf("[GAME SCENE]\n");
    printf("--------------------------------------------------\n");
    printf("%s: \"%s\"\n", heroName, dialogue);
    printf("--------------------------------------------------\n");
    printf("%s: \"크크크... 가당치도 않구나, %s!\"\n", npcName, heroName);
    printf("--------------------------------------------------\n\n");

    // [5] 문자열의 끝 '\0'의 위력 실험
    // heroName[7] 위치(공백 부분)에 강제로 '\0'을 넣으면 어떻게 될까?
    printf("[STRING TERMINATOR TEST]\n");
    heroName[7] = '\0'; // "Warrior" 뒤를 강제로 끊어버림
    printf("- 잘려버린 이름: %s\n", heroName);
    printf("- 하지만 메모리 뒤편에는 여전히 데이터가 있음: %c\n", heroName[8]);
    
    return 0;
}
