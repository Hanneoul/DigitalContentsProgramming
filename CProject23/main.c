/*
 * =========================================================================
 * [표준 vs 비표준 라이브러리 한눈에 보기]
 * =========================================================================
 * 1. 표준 라이브러리 (Standard Library)
 * - 특징: ISO 규격에 따라 모든 컴파일러에서 동일하게 제공함.
 * - 장점: "이식성"이 좋음. 내가 짠 코드가 리눅스 서버에서도 잘 돌아감.
 * - 단점: OS 고유의 강력한 기능(색상 변경, 하드웨어 제어)은 못 다룸.
 *
 * 2. 비표준 라이브러리 (Platform-Specific Library)
 * - 특징: 특정 OS(Windows 등)의 기능을 끌어다 쓰기 위해 만든 것.
 * - 장점: 하드웨어를 직접 주무를 수 있음. 게임다운 게임을 만들 수 있음.
 * - 단점: 윈도우 전용 코드가 되어버려 다른 OS에서는 컴파일 에러가 남.
 *
 *
 * =========================================================================
 * [실습: string.h로 배우는 배열과 포인터]
 * =========================================================================
 * 1. strlen(주소): NULL(\0)을 만날 때까지 칸을 세어 길이를 반환함.
 * 2. strcpy(대상주소, 원본주소): 원본 기차의 내용을 대상 기차로 복사함.
 * 3. strcmp(주소A, 주소B): 두 기차의 내용이 같은지 칸마다 비교함.
 * =========================================================================
 */
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <string.h>

int main() 
{
    // [1] 배열로 문자열 선언 (메모리에 공간 확보)
    char heroName[20] = "Magician";
    char enemyName[20];

    // [2] strcpy: 포인터(주소)를 이용한 데이터 복사
    // enemyName은 배열의 이름이자, 첫 번째 칸의 '주소'임.
    strcpy(enemyName, "Slime");

    // [3] strlen: 주소부터 시작해서 \0까지의 길이를 잼
    printf("영웅 이름: %s (길이: %zu)\n", heroName, strlen(heroName));
    printf("몬스터 이름: %s (길이: %zu)\n", enemyName, strlen(enemyName));

    // [4] strcmp: 두 주소의 내용을 비교 (같으면 0 반환)
    if (strcmp(heroName, "Warrior") == 0) 
    {
        printf("당신은 전사 클래스입니다.\n");
    }
    else
    {
        printf("당신은 전사가 아닙니다.\n");
    }

    // [5] 포인터의 맛보기
    // 배열 이름 heroName은 사실 &heroName[0]과 같은 주소값임.
    printf("heroName의 메모리 주소: %p\n", (void*)heroName);
    printf("네 번째 글자: %c\n", *(heroName+3)); // 포인터를 역참조하여 'W' 출력
    printf("네 번째 글자: %c\n", heroName[3]); // 포인터를 역참조하여 'W' 출력heroName[3]

    return 0;
}