/*
================================================================================
 [중급 가이드: 월드 좌표계 vs 화면 좌표계와 스크롤의 원리]
================================================================================

 1. 월드 좌표계 (World Coordinate)
 -------------------------------------------------------------------------
 - 게임 속 '진짜 세상'의 절대적인 위치임.
 - 예: 맵의 전체 가로 길이가 200이라면, 캐릭터는 0부터 200 사이 어디든 존재할 수 있음.
 - 캐릭터가 오른쪽으로 계속 가도 캐릭터의 '월드 x좌표'는 계속 커짐.

 2. 화면 좌표계 (Screen/View Coordinate)
 -------------------------------------------------------------------------
 - 플레이어의 '모니터' 안에서 실제로 보이는 위치임.
 - 예: 우리 터미널 창이 가로 40칸짜리라면, 화면 좌표는 무조건 0~39 사이여야 함.
 - 월드 좌표가 100인 나무가 있어도, 카메라가 100 위치에 있다면 화면 좌표는 0이 됨.

 3. 스크롤의 마법: "공식 하나로 해결함"
 -------------------------------------------------------------------------
 - [공식] 화면 좌표 = 월드 좌표 - 카메라 좌표
 - 카메라가 오른쪽으로 이동하면(카메라 x 증가), 모든 물체는 상대적으로 왼쪽으로
   밀려남(화면 x 감소). 이것이 우리가 느끼는 '스크롤'의 정체임.

 4. 렌더링 최적화 (Culling)
 -------------------------------------------------------------------------
 - 월드에 물체가 10,000개 있어도, "화면 좌표" 계산 결과가 0~39 사이인 것들만
   실제로 `draw_pixel`을 호출해서 그림. 화면 밖의 것은 그리지 않는 것이 성능의 핵심임.

================================================================================
*/

#include <stdio.h>

#define SCR_W 40       // 화면(터미널) 가로 크기
#define SCR_H 25       // 화면(터미널) 세로 크기
#define WORLD_W 100    // 전체 월드 가로 길이 (화면보다 훨씬 넓음)

// [함수] 화면 좌표계에 점 찍기 (이전과 동일)
void draw_pixel(int scrX, int scrY, int r, int g, int b) 
{
    if (scrX < 0 || scrX >= SCR_W || scrY < 0 || scrY >= SCR_H) return;
    printf("\033[%d;%dH", scrY + 1, (scrX * 2) + 1);
    printf("\033[48;2;%d;%d;%dm  \033[0m", r, g, b);
}

int main() 
{
    int playerWorldX = 10;  // 플레이어의 '월드' 내 위치
    int cameraX = 0;        // 카메라의 '월드' 내 위치
    char input;

    // 초기 설정 (화면 지우기, 커서 숨기기)
    printf("\033[2J\033[?25l");

    while (1) 
    {
        // 1. 카메라 위치 동기화 (플레이어를 화면 중앙에 두려고 노력함)
        // 카메라 위치 = 플레이어 위치 - 화면 절반
        cameraX = playerWorldX - (SCR_W / 2);

        // 카메라가 월드 경계를 벗어나지 않게 보정 (Clamp)
        if (cameraX < 0) cameraX = 0;
        if (cameraX > WORLD_W - SCR_W) cameraX = WORLD_W - SCR_W;

        // 2. 화면 그리기 (렌더링 루프)
        // 배경 그리기 (월드 좌표 10칸마다 나무나 기둥이 있다고 가정)
        int x = 0, y = 0;
        for (y = 10; y < SCR_H-10; y++) 
        {
            for (x = 0; x < SCR_W; x++) 
            {
                draw_pixel(x, y, 20, 20, 40); // 기본 배경(어두운 색)
            }
        }

        // 월드에 존재하는 지형지물(예: 기둥들) 그리기
        int worldX = 0;
        for (worldX = 0; worldX < WORLD_W; worldX += 10) 
        {
            // [핵심] 월드 좌표를 화면 좌표로 변환!!
            int screenX = worldX - cameraX;

            // 화면 안에 들어올 때만 그림
            for (y = 11; y < 14; y++) 
            {
                draw_pixel(screenX, y, 100, 100, 100); // 회색 기둥
            }
        }

        // 플레이어 그리기
        int playerScreenX = playerWorldX - cameraX;
        draw_pixel(playerScreenX, SCR_H / 2, 255, 255, 0); // 노란색 플레이어

        // 3. UI 및 안내 출력
        printf("\033[%d;1H", SCR_H + 2);
        printf(" [World X: %3d] [Camera X: %3d] [Screen X: %3d] \n",
            playerWorldX, cameraX, playerScreenX);
        printf(" 조작: a(좌), d(우) / 종료: q  >> ");

        // 4. 입력 처리
        input = getch();
        if (input == 'a' && playerWorldX > 0) 
            playerWorldX--;
        if (input == 'd' && playerWorldX < WORLD_W - 1) 
            playerWorldX++;
        if (input == 'q') 
            break;

        // 화면 갱신을 위해 잔상 제거 (실제 게임에선 버퍼를 쓰지만 여기선 간단히 지움)
        printf("\033[2J");
    }

    printf("\033[?25h\033[2J"); // 커서 복원 및 화면 정리
    return 0;
}