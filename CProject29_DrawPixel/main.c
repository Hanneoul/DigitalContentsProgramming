/*
================================================================================
 [초보자를 위한 C언어 콘솔 그래픽 & 좌표계 완벽 가이드]
================================================================================

 1. 가상 픽셀(Virtual Pixel)의 원리: "공백에 색을 입히면 점이 된다!"
 -------------------------------------------------------------------------
 - 터미널은 원래 '글자'를 찍는 곳이지 '그림'을 그리는 곳이 아님[cite: 1].
 - 하지만 우리는 '배경색이 있는 공백'을 출력해서 이를 하나의 점(Pixel)으로 활용함[cite: 1].

 - [핵심: 왜 공백을 두 칸("  ")이나 쓸까?]
   우리가 쓰는 글꼴은 대개 세로가 가로보다 훨씬 김(약 2:1 비율).
   만약 공백을 한 칸만 찍으면 픽셀이 홀쭉한 막대기처럼 보임.
   그래서 공백 두 칸을 붙여서 출력해야 우리 눈에 예쁜 '정사각형' 픽셀이 됨[cite: 1].

 2. 좌표계 매핑(Coordinate Mapping): "내가 원하는 곳에 점 찍기"
 -------------------------------------------------------------------------
 - [ANSI 커서 제어 문법]: \033[y;xH
   이 명령은 "y번째 줄, x번째 칸으로 마우스 커서를 순간 이동시켜!"라는 뜻임[cite: 1].
   이걸 이용하면 타자기처럼 순서대로 글을 안 써도 되고, 화면 어디든 점을 찍을 수 있음.

 - [좌표 계산의 비밀 (x * 2)]:
   위에서 픽셀 하나를 만들 때 공백을 '두 칸' 썼기 때문에,
   논리적인 x좌표가 1만큼 커질 때마다 실제 터미널 칸수는 2칸씩 옆으로 이동해야 함.
   그래서 코드에서 실제 출력 위치를 (x * 2)로 계산하는 것임[cite: 1].

 3. 트루 컬러(True Color) 시스템
 -------------------------------------------------------------------------
 - 문법: \033[48;2;R;G;Bm
 - R(빨강), G(초록), B(파랑) 값을 각각 0~255 사이로 조절해서 1,600만 가지 색을 만듦.
 - 48은 '배경색'을 바꾸겠다는 뜻이고, 2는 '트루 컬러' 모드를 쓰겠다는 약속임.

================================================================================
*/

#include <stdio.h>

/**
 * [함수: draw_pixel]
 * 설명: 화면의 특정 좌표(x, y)에 지정한 RGB 색상의 사각형 점을 찍음.
 */
void draw_pixel(int x, int y, int r, int g, int b)
{
    // 1. ANSI 명령어로 커서를 이동시킴.
    // 터미널 좌표는 (1, 1)부터 시작하므로 입력값에 +1을 해줌.
    // x는 가로 비율 보정을 위해 반드시 2를 곱해줌 (공백 2칸을 픽셀 하나로 쓰니까!)[cite: 1].
    printf("\033[%d;%dH", y + 1, (x * 2) + 1);

    // 2. 배경색을 설정하고 공백 두 칸을 출력함.
    // \033[0m은 색상 설정을 초기화하는 명령임. 이걸 안 하면 다음 글자까지 다 색칠됨.
    printf("\033[48;2;%d;%d;%dm  \033[0m", r, g, b);
}

/**
 * [함수: clear_canvas]
 * 설명: 화면 전체를 도화지처럼 한 가지 색으로 싹 칠해버림.
 */
void clear_canvas(int width, int height, int r, int g, int b)
{
    int x = 0, y = 0;
    for (y = 0; y < height; y++)
    {
        for (x = 0; x < width; x++)
        {
            draw_pixel(x, y, r, g, b);
        }
    }
}

/**
 * [함수: draw_big_smiley]
 * 설명: 원의 방정식을 응용해서 커다란 스마일 캐릭터를 그림.
 */
void draw_big_smiley(int centerX, int centerY, int radius)
{
    int x = 0, y = 0;

    // 1. 얼굴 그리기 (노란색 원)
    // 원의 방정식: (x - 중심x)^2 + (y - 중심y)^2 <= 반지름^2
    for (y = centerY - radius; y <= centerY + radius; y++)
    {
        for (x = centerX - radius; x <= centerX + radius; x++)
        {
            int dx = x - centerX;
            int dy = y - centerY;
            if (dx * dx + dy * dy <= radius * radius)
            {
                draw_pixel(x, y, 255, 255, 0); // 쨍한 노란색 얼굴
            }
        }
    }

    // 2. 눈 그리기 (검정색 픽셀)
    draw_pixel(centerX - 3, centerY - 2, 0, 0, 0); // 왼쪽 눈
    draw_pixel(centerX + 3, centerY - 2, 0, 0, 0); // 오른쪽 눈

    // 3. 입 그리기 (빨간색 스마일 라인)
    // 좌표를 직접 찍어서 웃는 모양을 만듦.
    draw_pixel(centerX - 4, centerY + 3, 255, 0, 0);
    draw_pixel(centerX - 3, centerY + 4, 255, 0, 0);
    draw_pixel(centerX - 2, centerY + 5, 255, 0, 0);
    draw_pixel(centerX - 1, centerY + 5, 255, 0, 0);
    draw_pixel(centerX, centerY + 5, 255, 0, 0);
    draw_pixel(centerX + 1, centerY + 5, 255, 0, 0);
    draw_pixel(centerX + 2, centerY + 5, 255, 0, 0);
    draw_pixel(centerX + 3, centerY + 4, 255, 0, 0);
    draw_pixel(centerX + 4, centerY + 3, 255, 0, 0);
}

int main(void)
{
    // [터미널 초기 설정]
    // \033[2J : 화면 전체를 지움
    // \033[?25l : 깜빡이는 커서를 숨겨서 그래픽이 깔끔하게 보이게 함
    printf("\033[2J\033[?25l");

    // 1. 도화지 준비 (가로 40, 세로 25 크기의 짙은 남색 배경)
    int w = 40, h = 25;
    clear_canvas(w, h, 30, 30, 70);

    // 2. 스마일 캐릭터 그리기
    // 화면 중앙쯤인 (20, 12) 좌표에 반지름 7짜리 스마일을 그림.
    draw_big_smiley(20, 12, 7);

    // 3. 마무리 및 설명 출력
    // 그림에 글자가 겹치지 않게 커서를 도화지 아래쪽으로 이동시킴.
    printf("\033[%d;1H\n", h + 2);
    printf(" [결과] 가상 픽셀로 구현한 잘생긴 교수님 얼굴!\n");

    // 프로그램 종료 전 커서를 다시 보이게 설정 (\033[?25h)
    printf("\033[?25h");

    return 0;
}