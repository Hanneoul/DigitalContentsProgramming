#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>
#include <windows.h> // 비동기 키 입력 및 프레임 제어용 API (Windows 환경)
#include <conio.h>   // _kbhit(), _getch() 함수 사용용
#include <time.h>    // 오늘 핵심 주인공 라이브러리

/*
================================================================================
[C언어 초보자를 위한 초정밀 핵심 강의자료: <time.h>와 표준 입출력 버퍼링]
================================================================================
이 자료는 C언어로 실시간 게임이나 멀티미디어 프로그램을 만들 때 반드시 알아야 하는
시간 제어 핵심 개념과 데이터 구조, 그리고 화면 출력 최적화 메커니즘을 다룸.

--------------------------------------------------------------------------------
1. <time.h> 라이브러리의 본질과 핵심 데이터 타입
--------------------------------------------------------------------------------
컴퓨터는 내부의 하드웨어 클록(Clock)을 이용하여 정밀하게 시간을 계산함.
<time.h>는 이 하드웨어 신호를 인간이나 프로그램이 쓸 수 있게 매핑해주는 내장 라이브러리임.

* time_t 타입:
  - "이 타입은 도대체 정체가 뭐야?" -> 내부적으로는 그냥 64비트 또는 32비트 '정수(Integer)'임.
  - 1970년 1월 1일 00:00:00 (UTC, 협정 세계시) 기준으로 현재까지 '몇 초(Seconds)'가
    흘렀는지를 저장하는 변수 타입임. 이를 '유닉스 타임(Unix Time)' 또는 '에포크 타임(Epoch Time)'이라 함.
  - 초 단위로 변하므로, 시스템의 현재 날짜나 난수 시드(Seed)를 잡을 때 주로 사용됨.

* clock_t 타입:
  - 이 녀석도 정체가 '정수형' 데이터 타입임.
  - 프로그램이 실행된 이후 CPU가 연산을 수행하면서 틱-톡 하며 소모한 '클록 틱(Clock Tick)' 카운트를 저장함.
  - OS마다 1초당 발생하는 클록 틱 횟수가 다른데, C언어에서는 이를 'CLOCKS_PER_SEC'이라는 상수로 매크로 정의해둠.
  - Windows 환경에서는 대개 1초에 1000 틱이 지나가므로, clock_t의 단위는 사실상 '밀리초(ms)' 단위와 호환됨.

* struct tm 구조체:
  - 초 단위 정수형 데이터(time_t)는 인간이 보기엔 "1719842400" 같은 해독 불가능한 숫자에 불과함.
  - 이를 인간이 읽을 수 있게 연, 월, 일, 시, 분, 초 단위로 쪼개서 멤버 변수로 가지고 있는 내장 구조체임.
  - 구조체 내부 구성 예시:
    int tm_sec;   // 초 (0 ~ 60)
    int tm_min;   // 분 (0 ~ 59)
    int tm_hour;  // 시 (0 ~ 23)
    int tm_mday;  // 일 (1 ~ 31)
    int tm_mon;   // 월 (0 ~ 11, ※주의: 0이 1월이므로 출력할 때는 반드시 +1 해야 함!)
    int tm_year;  // 연도 (※주의: 1900년도부터 흘러온 연도이므로 출력할 때는 반드시 +1900 해야 함!)
    int tm_wday;  // 요일 (0: 일요일 ~ 6: 토요일)

--------------------------------------------------------------------------------
2. 핵심 시간 함수 사용법
--------------------------------------------------------------------------------
* time(NULL);
  - 현재 시스템의 '초 단위 시간'을 가져옴. 변수에 대입하거나 `srand((unsigned int)time(NULL));`
    처럼 호출하여 프로그램 실행 시마다 매번 완벽히 다른 난수(Random Number) 배열을 생성하는 시드로 활용함.

* clock();
  - 현재 호출된 순간의 CPU 클록 카운트를 딱 찍어서 반환함.
  - 코드 시작할 때 한번 찍고, 끝날 때 한번 찍어서 둘을 빼면(`종료클록 - 시작클록`)
    해당 연산이 수행되는 데 몇 클록이 소모되었는지 계산 가능함.
  - 여기에 `(double)CLOCKS_PER_SEC`로 나눠주면 정확히 '몇 초' 걸렸는지 소수점까지 구해짐.

================================================================================
[미니 게임 매뉴얼: 노랭이의 무한 질주 (Dino Run C-Style Clone)]
================================================================================
1. 게임 콘셉트
   - 구글 크롬의 인터넷 연결 끊겼을 때 나오는 공룡 게임을 C언어 콘솔 환경으로 오마주.
   - 2글자의 공백("  ")을 하나의 픽셀(Pixel) 블록으로 간주하고 ANSI 컬러를 입혀 비주얼 구현.

2. 조작 방법 및 시스템
   - [스페이스바] 또는 [Z] 또는 [z]: 노랭이 점프 조작.
   - [Q] 또는 [q]: 언제든 현생으로 탈출 가능한 빡종 키.
   - 장애물을 하나씩 통과할 때마다 점수가 10점씩 누적되며 게임의 루프 속도가 점차 빨라짐.
================================================================================
*/

// 글로벌 물리 매크로 및 화면 규격 설정
#define SCREEN_WIDTH 40       // 게임 가로 폭 (공백 2칸 기준 40칸 = 총 80글자 너비)
#define GROUND_Y 10           // 바닥면이 위치할 Y축 높이 고정 값
#define GRAVITY 1             // 매 프레임 주인공을 아래로 끌어내리는 가상의 중력 가속도 값

// ANSI Escape Sequence 기반 컬러 코드 정의 (가독성 증진용)
#define ANSI_CLR "\x1b[H"               // 콘솔 화면 커서를 무조건 좌측 최상단(0,0)으로 강제 강제 리셋
#define ANSI_BG_SKY "\x1b[48;5;111m"    // 배경 화면을 채울 화사한 하늘색 (Extended 256 컬러 모드)
#define ANSI_HERO "\x1b[43m"            // 주인공 노랭이 블록을 채울 노란색 배경 컬러 코드
#define ANSI_OBS "\x1b[41m"             // 장애물을 표시할 위협적인 빨간색 배경 컬러 코드
#define ANSI_RESET "\x1b[0m"            // 적용된 색상 서식을 해제하고 기본 콘솔 상태로 되돌리는 코드

int main(void) 
{
    // -------------------------------------------------------------------------
    // [강의 내용 실전 적용 1] <time.h>를 이용한 난수 발생기 초기화
    // -------------------------------------------------------------------------
    // 실행할 때마다 컴퓨터 시간(초 데이터)이 매번 바뀌므로 완벽히 불규칙한 시드가 잡힘.
    srand((unsigned int)time(NULL));

    // 게임에 필요한 원시 상태 변수 선언 및 초기화 (철저한 C언어 스타일)
    int heroY = GROUND_Y;       // 주인공의 현재 Y 좌표 (초기 상태는 바닥에 서 있음)
    int heroVelocity = 0;       // 주인공의 Y축 이동 속도 (0이면 정지, 음수면 상승, 양수면 하강)
    bool isJumping = false;     // 현재 공중에 떠 있는 점프 상태인지 여부를 판별하는 플래그

    int obsX = SCREEN_WIDTH - 2;// 장애물의 현재 X 좌표 (초기엔 화면 맨 오른쪽 끝에서 등장 대기)
    int score = 0;              // 플레이어의 현재 점수 스코어 변수
    int gameSpeed = 50;         // 루프 한 바퀴당 강제 대기할 시간(ms). 이 숫자가 줄어들수록 겜이 빨라짐!

    // Windows 콘솔 창에서 끔찍하게 깜빡거리는 텍스트 커서( _ )를 강제로 숨기는 OS 특수 설정
    HANDLE consoleHandle = GetStdHandle(STD_OUTPUT_HANDLE);
    CONSOLE_CURSOR_INFO cursorInfo;
    GetConsoleCursorInfo(consoleHandle, &cursorInfo);
    cursorInfo.bVisible = FALSE; // 커서 가시성을 비활성화(False) 처리
    SetConsoleCursorInfo(consoleHandle, &cursorInfo);

    // -------------------------------------------------------------------------
    // [강의 내용 실전 적용 2] setvbuf를 활용한 버퍼링 모드 변경 (Full Buffering)
    // -------------------------------------------------------------------------
    // stdout(표준출력) 스트림에 10KB(10240 바이트) 짜리 거대한 내부 버퍼 장바구니를 할당함.
    // _IOFBF 모드이므로 이제 printf를 아무리 갈겨도 모니터에 바로 안 나오고 버퍼 메모리에만 적재됨.
    setvbuf(stdout, NULL, _IOFBF, 10240);

    // 최초 실행 시 기존 콘솔 창의 지저분한 텍스트를 깨끗하게 밀어버리는 스크린 클리어 시퀀스
    printf("\x1b[2J");

    // =========================================================================
    // 메인 게임 루프 진입 (실시간으로 무한 반복 실행됨)
    // =========================================================================
    while (true) 
    {

        // ---------------------------------------------------------------------
        // 1. 실시간 비동기 키 입력 처리부 (_kbhit / _getch)
        // ---------------------------------------------------------------------
        // _kbhit()은 키보드가 눌렸을 때 프로그램의 흐름을 멈추지 않고 즉시 true를 반환함. (개사기 함수)
        if (_kbhit()) 
        {
            int key = _getch(); // 실제로 어떤 키가 눌렸는지 입력 버퍼에서 한 글자 쏙 빼옴.

            // 현실 도피용 빡종 처리 키 검사
            if (key == 'q' || key == 'Q')
            {
                break; // 게임 루프 즉시 탈출
            }

            // 점프 조건 검사: 스페이스바(' ') 혹은 대소문자 Z/z 키가 눌렸고, 이미 점프한 상태가 아닐 때만!
            if ((key == 'z' || key == 'Z' || key == ' ') && !isJumping) 
            {
                isJumping = true;      // 점프 상태 활성화
                heroVelocity = -3;     // 위쪽 방향으로 솟구치도록 속도를 음수 값으로 부여 (화면 Y축은 내려갈수록 커짐)
            }
        }

        // ---------------------------------------------------------------------
        // 2. 물리 엔진(?) 및 게임 상태 객체 업데이트부
        // ---------------------------------------------------------------------
        if (isJumping)
        {
            heroY += heroVelocity;    // 속도 값만큼 실제 주인공의 Y 위치를 변화시킴
            heroVelocity += GRAVITY;  // 중력 상수를 지속적으로 누적 더해줘서 상승 속도를 꺾고 하강하게 만듦

            // 주인공이 땅바닥으로 떨어졌을 때의 예외 처리 (착지 판정)
            if (heroY >= GROUND_Y) 
            {
                heroY = GROUND_Y;     // 바닥을 뚫고 지하바닥으로 내려가지 못하게 고정
                isJumping = false;    // 점프 상태 종료
                heroVelocity = 0;     // Y축 이동 속도 초기화
            }
        }

        // 장애물 이동 제어: 매 프레임마다 왼쪽으로 한 칸씩 돌진해옴
        obsX--;

        // 장애물이 화면 왼쪽 끝 경계선을 넘어가서 소멸했을 때의 처리
        if (obsX < 0) 
        {
            obsX = SCREEN_WIDTH - 2;   // 다시 화면 맨 오른쪽 끝으로 부활(리스폰) 시킴
            score += 10;              // 장애물을 완벽히 무빙으로 피했으므로 10점 상납함

            // [난이도 상승 시스템] 스코어가 쌓일 때마다 딜레이 타임을 깎아서 강제로 겜 속도를 올림
            if (gameSpeed > 15) 
            {
                gameSpeed -= 2;        // 최저 마지노선 15ms 전까지 프레임 속도를 점진적으로 타이트하게 조임
            }
        }

        // ---------------------------------------------------------------------
        // 3. 충돌 검사 처리부 (Collision Detection)
        // ---------------------------------------------------------------------
        // 주인공은 언제나 X축 좌표 기준 4번~5번 영역에 고정되어 러닝 머신을 뛰고 있는 상태임.
        // 따라서 밀려오는 장애물의 X좌표가 4 혹은 5에 도달했을 때, 주인공이 점프 안 하고 바닥(GROUND_Y)에 있다면? 쿵!
        if (obsX == 5 && heroY == GROUND_Y) 
        {
            printf(ANSI_CLR); // 화면 초기화 위치로 이동
            printf("\n\n ==========================================\n");
            printf(" [ GAME OVER ] 풉\n");
            printf(" 최종 점수: %d 점 획득함.\n", score);
            printf(" ==========================================\n");
            printf(" 킹받죠? 복수하고 싶으면 프로그램 재실행하셈.\n\n");

            // 게임오버 메시지가 출력 버퍼에 갇혀 안 나오는 것을 막기 위해 마지막 강제 방출
            fflush(stdout);
            break; // 루프 박살내고 메인 함수 종료 절차 밟기
        }

        // ---------------------------------------------------------------------
        // 4. 실시간 터미널 2D 그래픽스 렌더링부 (ANSI Escape Sequence)
        // ---------------------------------------------------------------------
        printf(ANSI_CLR); // 매 프레임을 그릴 때마다 커서를 (0,0)으로 보내서 위에다 덧그림 (깜빡임 최소화)

        // 최상단 디스플레이 상태창 렌더링
        printf(" CURRENT SCORE: %04d 점 | 빡종: Q | 점프: Z 또는 SPACE\n", score);

        // 2차원 공간 (Y축 루프 안에 X축 루프 구조) 전체 순회하며 픽셀 그리기
        for (int y = 0; y <= GROUND_Y+1; y++) 
        {
            for (int x = 0; x < SCREEN_WIDTH; x++) 
            {

                // 조건 1: 현재 좌표가 주인공의 물리 위치(X가 5 이고 Y가 heroY)와 일치하면 노랭이 픽셀 투척
                if (y == heroY && x == 5) 
                {
                    printf(ANSI_HERO "  " ANSI_RESET);
                }
                // 조건 2: 현재 좌표가 장애물의 위치(Y가 바닥이고 X가 obsX~obsX+1)와 일치하면 뻘건 장애물 투척
                else if (y == GROUND_Y && (x == obsX || x == obsX + 1)) 
                {
                    printf(ANSI_OBS "  " ANSI_RESET);
                }
                // 조건 3: Y축이 바닥 라인인 경우 길바닥 렌더링 (회색 언더바 적용)
                else if (y == GROUND_Y+1) 
                {
                    printf("\x1b[48;5;242m__" ANSI_RESET);
                }
                // 조건 4: 그 외의 빈 공간은 전부 드넓고 푸른 하늘색 배경으로 도배 처리
                else 
                {
                    printf(ANSI_BG_SKY "  " ANSI_RESET);
                }
            }
            printf("\n"); // 가로 한 줄 다 그렸으면 개행해서 다음 줄로 이동
        }

        // ---------------------------------------------------------------------
        // [강의 내용 실전 적용 3] fflush를 통한 임시 버퍼 데이터 모니터로 일제 방출!
        // ---------------------------------------------------------------------
        // 이 타이밍에 호출을 안 해주면 setvbuf(_IOFBF) 때문에 모니터가 먹통이 됨.
        // 메모리 버퍼 속에 완성된 완벽한 한 프레임의 그림을 이 순간 모니터 화면에 단 한 방에 쾅! 찍어줌.
        fflush(stdout);

        // 컴퓨터 연산 속도가 너무 빠르므로 지정된 ms(밀리초) 만큼 흐름을 강제 홀딩 (프레임 스피드 조절)
        Sleep(gameSpeed);
    }

    return 0;
}