/*
=============================================================================
[강의 자료: scanf_s()를 통한 안전한 문자열 입력과 string.h 활용법]
=============================================================================

1. 왜 scanf_s()인가? (Visual Studio의 보안 요구사항)
   - 전통적인 scanf()는 문자열(%s)을 입력받을 때, 저장 공간(배열)의 크기를 넘어가는
     대형 문자열이 들어와도 제어하지 못함. 이는 메모리가 오염되는 '버퍼 오버플로우'
     취약점을 유발하여 프로그램이 강제 종료되거나 해킹에 노출될 수 있음.
   - C11 표준 및 최신 Visual Studio 환경에서는 이를 방지하기 위해 안전망이 강화된
     scanf_s() 사용을 강력히 권장함.

2. scanf_s() 문자열 입력의 핵심: 버퍼 크기(Buffer Size) 명시
   - 기본 문법: scanf_s("%s %s", 배열1, (unsigned)sizeof(배열1), 배열2, (unsigned)sizeof(배열2));
   - 정수(%d)나 실수(%f)는 기존 scanf()와 사용법이 완전히 같음 (크기를 명시할 필요 없음).
   - 단, 문자(%c)와 문자열(%s)을 입력받을 때는 서식 지정자 매칭 뒤에 반드시
     "그 데이터를 받아줄 메모리 방의 최대 크기"를 인자로 명시해야 함.
   - 만약 입력된 문자열의 길이가 지정된 배열의 크기(널 문자 포함)를 초과하면,
     scanf_s는 값을 저장하지 않고 데이터를 무효화(NULL 처리)하여 메모리를 안전하게 보호함.

3. <string.h> 라이브러리의 핵심 함수 이해
   - C언어에서 문자열은 char 타입 배열의 형태를 가지므로, `if (action == "이동")` 같은
     일반 비교 연산자로 문자열의 실제 알맹이를 비교할 수 없음.

     ① strcmp(문자열1, 문자열2) -> String Compare
        - 두 문자열의 내용물이 일치하는지 메모리 바이트 단위로 대조하는 함수.
        - 결과값이 '0'이면 두 문자열의 내용이 완전히 일치함을 의미함.
        - 예: if (strcmp(action, "이동") == 0) -> 사용자가 "이동"을 입력했는지 검증.

     ② strcpy_s(대상배열, 크기, 원본문자열) -> String Copy (안전 버전)
        - 문자열은 대입 연산자(=)로 통째로 복사할 수 없으므로 이 함수를 사용함.
        - 특정 방에 아이템이나 텍스트 정보를 안전하게 밀어 넣을 때 필수적임.

4. 복합 단어 커맨드 파싱 룰 (MUD 스타일)
   - scanf_s("%s %s", action, target) 구조는 공백(스페이스바)을 기준으로 단어를 쪼갬.
   - 사용자가 "이동 서재"라고 입력하면 action에는 "이동"이, target에는 "서재"가
     동시에 완벽하게 분리되어 안착함.
=============================================================================
*/

#include <stdio.h>
#include <string.h> // strcmp, strcpy_s 함수 사용을 위한 헤더

int main() 
{
    // [게임 상태 변수 선언]
    int current_room = 1;  // 1: 어두운 방, 2: 먼지 쌓인 서재, 3: 비밀 통로
    int key_state = 1;     // 1: 방에 떨어져 있음, 0: 플레이어가 주움, -1: 이미 사용함

    // [문자열 입력 저장 공간] - 한글은 글자당 크기가 크므로 넉넉하게 할당
    char action[20] = "";
    char target[20] = "";

    // [게임 시작 인트로]
    printf("===============================================================\n");
    printf("         TEXT MUD: 의문의 방 탈출 게임 (scanf_s 기반)          \n");
    printf("===============================================================\n");
    printf(" 눈을 떠보니 사방이 막힌 낯선 공간에 갇혀 있습니다.\n");
    printf(" [명령어 대상] 구조로 행동을 지시하십시오.\n");
    printf(" (예시: 이동 서재 | 조사 침대 | 줍기 열쇠 | 사용 열쇠)\n");
    printf("===============================================================\n\n");

    // [게임 메인 루프]
    while (1) 
    {
        printf("---------------------------------------------------------------\n");

        // [현재 맵 환경 제어 화면]
        if (current_room == 1) 
        {
            printf("[현재 위치: 어두운 방]\n");
            printf("낡은 침대가 덩그러니 놓여 있고, 정면에는 굳게 잠긴 철문이 보입니다.\n");
            printf("오른쪽 벽면에는 서재로 통하는 열린 통로가 있습니다.\n");
            if (key_state == 1) 
            {
                printf("⚠️  침대 밑 먼지 구덩이 속에 바닥에 떨어진 [열쇠]가 언뜻 보입니다.\n");
            }
        }
        else if (current_room == 2) 
        {
            printf("[현재 위치: 먼지 쌓인 서재]\n");
            printf("거대한 책상과 수많은 책이 꽂힌 거대한 책장이 보입니다.\n");
            printf("왼쪽 통로를 통해 다시 원래 있던 어두운 방으로 돌아갈 수 있습니다.\n");
        }
        else if (current_room == 3) 
        {
            printf("[현재 위치: 비밀 통로]\n");
            printf("책장이 스르륵 열리며 나타난 비밀 공간입니다.\n");
            printf("벽면에 외부세계와 연결된 탈출용 레버가 설치되어 있습니다.\n");
        }

        // [명령어 입력 받기]
        printf("\n>> 행동 명령 입력(이동/조사/줍기/사용) : ");

        /* [scanf_s 핵심 구현 포인트]
           - %s 서식 뒤에 각각 입력받을 문자열 배열의 실제 크기인 `sizeof(변수)`를 반드시 인자로 넘겨야 함.
           - 사용자가 단어 하나만 치고 엔터를 누르거나 잘못된 입력을 했을 때를 대비하여 리턴값 개수(2개 단어)를 체크함.
        */
        int input_result = scanf_s("%s %s", action, (unsigned)sizeof(action), target, (unsigned)sizeof(target));

        // 입력 스트림 오류 처리 및 비정상 입력 대기실 청소
        if (input_result != 2) 
        {
            printf("\n[시스템 인터럽트] 명령은 반드시 '[명령어] [대상]' 두 단어로 입력해야 합니다.\n");
            while (getchar() != '\n'); // 입력 버퍼 청소
            continue;
        }

        printf("---------------------------------------------------------------\n");
        printf("[행동 로그] 수행 작업: %s | 대상 목적물: %s\n", action, target);
        printf("---------------------------------------------------------------\n\n");

        // =================================================================
        // [ROOM 1: 어두운 방 제어 로직]
        // =================================================================
        if (current_room == 1)
        {
            if (strcmp(action, "이동") == 0) 
            {
                if (strcmp(target, "서재") == 0) 
                {
                    printf("[결과] 서재 안쪽으로 조용히 걸어 들어갑니다.\n");
                    current_room = 2;
                }
                else if (strcmp(target, "철문") == 0 || strcmp(target, "방") == 0) 
                {
                    printf("[결과] 문이 잠겨 있어 이동할 수 없습니다. 먼저 문을 열어야 합니다.\n");
                }
                else 
                {
                    printf("[결과] 이곳에서는 그 장소로 이동할 수 없습니다.\n");
                }
            }
            else if (strcmp(action, "조사") == 0) 
            {
                if (strcmp(target, "침대") == 0) 
                {
                    if (key_state == 1) 
                    {
                        printf("[결과] 침대 및 먼지 속에서 구르던 [열쇠]의 위치를 정확하게 파악했습니다.\n");
                    }
                    else 
                    {
                        printf("[결과] 침대 밑에는 굴러다니는 먼지 덩어리 외엔 아무것도 없습니다.\n");
                    }
                }
                else if (strcmp(target, "철문") == 0) 
                {
                    printf("[결과] 정밀하게 만들어진 강철문입니다. 열쇠 구멍이 정중앙에 있습니다.\n");
                }
                else 
                {
                    printf("[결과] 조사할 수 없는 대상이거나 유효하지 않은 물체입니다.\n");
                }
            }
            else if (strcmp(action, "줍기") == 0) 
            {
                if (strcmp(target, "열쇠") == 0) 
                {
                    if (key_state == 1) 
                    {
                        printf("[결과] 바닥을 더듬어 녹슨 [열쇠]를 획득하여 주머니에 넣었습니다.\n");
                        key_state = 0; // 플레이어 인벤토리 보유 상태로 변경
                    }
                    else if (key_state == 0) 
                    {
                        printf("[결과] 열쇠는 이미 요원의 주머니 속에 보관되어 있습니다.\n");
                    }
                    else 
                    {
                        printf("[결과] 열쇠는 이미 자물쇠에 사용되어 사라졌습니다.\n");
                    }
                }
                else 
                {
                    printf("[결과] 이곳에는 주울 수 있는 그런 물건이 존재하지 않습니다.\n");
                }
            }
            else if (strcmp(action, "사용") == 0) 
            {
                if (strcmp(target, "열쇠") == 0) 
                {
                    if (key_state == 0) 
                    {
                        printf("[결과] 철문 자물쇠에 열쇠를 넣고 돌리자 딸깍 소리와 함께 문이 열립니다.\n");
                        printf("★ 일반 탈출 성공! 안전한 복도로 걸어 나갑니다. (Normal Ending) ★\n");
                        return 0; // 프로그램 정상 종료
                    }
                    else 
                    {
                        printf("[결과] 현재 보유하고 있는 열쇠가 없습니다.\n");
                    }
                }
                else 
                {
                    printf("[결과] 그것은 여기에서 사용할 수 없는 아이템입니다.\n");
                }
            }
            else 
            {
                printf("[알림] 알 수 없는 명령어입니다. (이동, 조사, 줍기, 사용 중에서 시도하십시오)\n");
            }
        }
        // =================================================================
        // [ROOM 2: 먼지 쌓인 서재 제어 로직]
        // =================================================================
        else if (current_room == 2) 
        {
            if (strcmp(action, "이동") == 0) 
            {
                if (strcmp(target, "방") == 0 || strcmp(target, "어두운방") == 0) 
                {
                    printf("[결과] 서재를 나와 다시 어둡고 낡은 침대가 있는 방으로 돌아갑니다.\n");
                    current_room = 1;
                }
                else if (strcmp(target, "비밀통로") == 0) 
                {
                    printf("[결과] 비밀 통로가 어딨는지 먼저 찾아내야 그리로 이동할 수 있습니다.\n");
                }
                else 
                {
                    printf("[결과] 그 방향으로는 연결된 통로나 방이 없습니다.\n");
                }
            }
            else if (strcmp(action, "조사") == 0) 
            {
                if (strcmp(target, "책상") == 0) 
                {
                    printf("[결과] 서랍을 전부 열어보았으나 텅 빈 종이 조각 외에는 쓸모 있는 아이템이 없습니다.\n");
                }
                else if (strcmp(target, "책장") == 0 || strcmp(target, "책") == 0) 
                {
                    printf("[결과] 책장 한구석에 제목이 적혀있지 않은 기묘한 특정 가죽 책 한 권이 튀어나와 있습니다.\n");
                }
                else 
                {
                    printf("[결과] 서재 내부의 해당 사물은 특이사항이 발견되지 않았습니다.\n");
                }
            }
            else if (strcmp(action, "당기기") == 0 || strcmp(action, "사용") == 0) 
            {
                if (strcmp(target, "책") == 0 || strcmp(target, "책장") == 0) 
                {
                    printf("[결과] 돌출된 가죽 책을 힘껏 잡아당기자 태엽 장치가 맞물리는 소리가 납니다!\n");
                    printf("       거대한 책장이 거구의 몸집을 물리치며 벽 뒤에 숨겨진 [비밀통로]를 드러냅니다.\n");
                    current_room = 3; // 강제 이동 처리
                }
                else 
                {
                    printf("[결과] 그것은 당기거나 작동시킬 수 있는 트리거 사물이 아닙니다.\n");
                }
            }
            else 
            {
                printf("[알림] 서재에서는 주로 '조사', '이동', '당기기' 커맨드가 유효합니다.\n");
            }
        }
        // =================================================================
        // [ROOM 3: 비밀 통로 제어 로직]
        // =================================================================
        else if (current_room == 3) 
        {
            if (strcmp(action, "이동") == 0) 
            {
                if (strcmp(target, "서재") == 0) 
                {
                    printf("[결과] 비밀 공간을 나와 다시 먼지 쌓인 서재 맵으로 복귀합니다.\n");
                    current_room = 2;
                }
                else 
                {
                    printf("[결과] 탈출 통로 내에서는 이동의 제약이 있습니다. 오직 서재로만 환원 가능합니다.\n");
                }
            }
            else if (strcmp(action, "당기기") == 0 || strcmp(action, "사용") == 0)
            {
                if (strcmp(target, "레버") == 0) 
                {
                    printf("[결과] 묵직한 무쇠 레버를 밑으로 가차 없이 내리 누릅니다.\n");
                    printf("       쿠쿠쿠쿵! 벽 전체가 통째로 회전하며 외부의 햇빛과 자유의 공기가 쏟아집니다.\n");
                    printf("★ 진 탈출 성공! 완벽하게 은닉된 특수 루트로 탈출을 완료했습니다! (True Ending) ★\n");
                    return 0; // 프로그램 격침 종료
                }
                else 
                {
                    printf("[결과] 이곳에는 당길 수 있는 대상이 '레버' 외엔 존재하지 않습니다.\n");
                }
            }
            else if (strcmp(action, "조사") == 0) {
                if (strcmp(target, "레버") == 0) {
                    printf("[결과] 외부 빗장을 개방할 수 있도록 설계된 기계식 대형 레버 장치입니다.\n");
                }
                else {
                    printf("[결과] 사방이 차가운 콘크리트 벽면 구조물로 둘러싸여 있습니다.\n");
                }
            }
            else {
                printf("[알림] 이 폐쇄망 안에서는 '당기기', '조사', '이동' 행위만 작동 승인됩니다.\n");
            }
        }
    }

    return 0;
}