/*
======================================================================
[강의 자료: printf 형식 지정자 및 서식 제어 완벽 가이드]

1. 기본 형식 지정자 (Data Types)
   - %d / %i  : 10진수 정수 (Integer)
   - %u       : 부호 없는 10진수 정수 (Unsigned Integer)
   - %f       : 실수 (Float / Double)
   - %c       : 문자 하나 (Character)
   - %s       : 문자열 (String)
   - %p       : 메모리 주소값 (Pointer)
   - %x / %X  : 16진수 (Hexadecimal) - 소문자/대문자 출력 구분
   - %o       : 8진수 (Octal)
   - %%       : % 기호 자체를 출력

2. 서식 제어 (Format Control)
   - 폭(Width)  : %[숫자]d -> 지정한 숫자만큼 칸을 확보 (오른쪽 정렬)
   - 정렬(Align): %-[숫자]d -> 지정한 숫자만큼 칸을 확보 (왼쪽 정렬)
   - 채우기(Fill): %0[숫자]d -> 빈칸을 공백 대신 0으로 채움
   - 정밀도(.Pre): %. [숫자]f -> 소수점 아래 자릿수 제한
                 %. [숫자]s -> 문자열의 최대 출력 길이를 제한

3. 이스케이프 시퀀스 (Escape Sequence)
   - \n : 줄바꿈 (New Line)
   - \t : 수평 탭 (Tab) - 간격 맞출 때 유용
   - \\ : 백슬래시 출력
   - \" : 큰따옴표 출력
======================================================================
*/

/*
======================================================================
[printf 심화 개념 정리]

1. 폭(Width): 출력할 최소 칸수를 지정함. 데이터가 이보다 작으면 공백으로 채움.
2. 정밀도(.Precision):
   - 실수: 소수점 아래 몇 자리까지 표시할지 결정.
   - 문자열: 최대 몇 글자까지만 출력할지 제한.
3. 플래그(Flags):
   - '-': 왼쪽 정렬 (기본은 오른쪽 정렬).
   - '+': 양수일 때도 + 기호를 강제로 표시.
   - '0': 남는 칸을 공백 대신 0으로 채움.
   - '#': 8진수(0), 16진수(0x) 등의 접두사를 자동으로 붙임.

① 필드 폭 (Field Width)
숫자를 써넣으면 그만큼의 최소 칸을 확보함.
데이터 리스트를 뽑을 때 줄을 맞추기 위해 필수적임 (예: 성적표, 장부).

② 정밀도 (Precision)
실수(%f)에서는 반올림 위치를 결정함.
문자열(%s)에서는 "최대 출력 길이"를 의미함. 긴 문장의 앞부분만 잘라서 보여줄 때 매우 유용함.

③ # 플래그 (Alternative Form)
8진수(%o)나 16진수(%x)를 출력할 때 각각 0, 0x를 자동으로 붙여줌.
주소값이나 하드웨어 레지스터 값을 확인할 때 가독성을 높여줌.

④ * (Asterisk) 와일드카드
가장 고급 기능 중 하나임. printf("%*d", 10, num); 처럼 사용하면, 폭(10)을 상수가 아닌 변수로 제어할 수 있음.
상황에 따라 출력 칸수가 변해야 하는 동적인 UI를 만들 때 사용함.

⑤ %n 지정자 (특수 기능)
화면에 출력하는 게 아니라, "지금까지 출력된 문자의 개수"를 변수에 저장함.
printf("Hello%n", &count); 라고 하면 count에는 5가 저장됨. (보안 취약점 때문에 최근엔 사용을 자제하는 추세이지만, 개념은 알아둘 만함.)

======================================================================
*/

#include <stdio.h>

int main() {
    int num = 123;
    double pi = 3.1415926535;
    char* str = "I hate Programming";

    // --- 1. 정수 심화 (폭과 플래그) ---
    printf("--- Integer Advanced ---\n");
    printf("[%01d]\n", num);      // 10칸 확보, 오른쪽 정렬
    printf("[%-10d]\n", num);     // 10칸 확보, 왼쪽 정렬 (-)
    printf("[%+d]\n", num);       // 양수 기호 표시 (+)
    printf("[%010d]\n", num);     // 10칸 확보, 빈칸은 0으로 채움 (0)
    printf("[%#x]\n", num);       // 16진수 출력 시 0x 접두사 붙임 (#)
    printf("\n");

    // --- 2. 실수 심화 (정밀도) ---
    printf("--- Float Advanced ---\n");
    printf("[%10.2f]\n", pi);     // 전체 10칸, 소수점 아래 2자리
    printf("[%10.5f]\n", pi);     // 전체 10칸, 소수점 아래 5자리
    printf("[%-10.3f]\n", pi);    // 왼쪽 정렬, 소수점 아래 3자리
    printf("\n");

    // --- 3. 문자열 심화 (부분 출력) ---
    printf("--- String Advanced ---\n");
    printf("[%20s]\n", str);      // 20칸 확보 후 문자열 출력
    printf("[%.5s]\n", str);      // 문자열 중 앞의 5글자만 출력 (정밀도 활용)
    printf("[%20.10s]\n", str);   // 20칸 확보하고, 앞의 10글자만 오른쪽 정렬 출력
    printf("\n");

    // --- 4. 동적 폭 지정 (가변 폭) ---
    // 코드 실행 중에 칸수나 정밀도를 결정하고 싶을 때 *를 사용함
    int width = 15;
    int precision = 4;
    printf("--- Dynamic Width ---\n");
    printf("[%*.*f]\n", width, precision, pi); // 15칸 확보, 소수점 4자리

    return 0;
}