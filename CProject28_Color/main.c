#include <stdio.h>

/*
================================================================================
[ANSI Escape Sequence Color Guide for Terminal Game Programming]
================================================================================
1. ANSI Escape Sequence 개요
   - 터미널의 커서 위치, 색상, 스타일 등을 제어하기 위한 표준 규격.
   - 접두사: \033 (8진수), \x1b (16진수), \e (GNU C 확장) -> 모두 ASCII의 Escape 문자(Dec 27)를 의미함.
   - 색상 변경 기본 구조: "\033[ [파라미터] m"
   - 색상 리셋 구조: "\033[0m" (출력 후 리셋하지 않으면 다음 출력까지 색상이 유지됨)

2. 비트(Bit) 단위에 따른 색상 표현력 및 원리
   - 컴퓨터는 0과 1(1비트)로 데이터를 표현함. 비트 수가 늘어날수록 표현 가능한 색상 수가 기하급수적으로 증가함.

   A. 3-bit Color (8가지 색상)
      - 원리: 빛의 3원색인 Red, Green, Blue를 각각 켜고 끄는(On/Off) 방식으로 1비트씩 할당함.
      - 수식: 2^3 = 8가지 조합
      - 조합 표:
        * 000 (전체 Off) -> 검은색 (Black)
        * 100 (Red만 On) -> 빨간색 (Red)
        * 010 (Green만 On) -> 초록색 (Green)
        * 001 (Blue만 On) -> 파란색 (Blue)
        * 110 (R+G On) -> 노란색 (Yellow)
        * 101 (R+B On) -> 보라색 (Magenta)
        * 011 (G+B On) -> 청록색 (Cyan)
        * 111 (전체 On) -> 흰색 (White)

   B. 4-bit Color (16가지 색상)
      - 원리: 기존 3-bit(R, G, B)에 '명도/밝기(Intensity/Bold)'를 제어하는 1비트를 추가함.
      - 수식: 2^4 = 16가지 조합
      - 특징: 기존 8가지 기본 색상에 각각 '어두운 버전'과 '밝은(고명도) 버전'이 존재하게 됨.
      - ANSI에서는 명령어 내에 '1;'을 추가하여 고명도(Bright)를 활성화함.

   C. 8-bit Color (256가지 색상)
      - 원리: 1바이트(8비트) 전체를 하나의 색상 인덱스로 활용함.
      - 수식: 2^8 = 256가지 조합 (0 ~ 255번 고유 번호 부여)
      - 내부 구역 구분:
        * 0 ~ 15 (16개): 기존 4-bit 시스템의 16색과 호환되는 영역
        * 16 ~ 231 (216개): R, G, B를 각각 6단계(0~5)로 나누어 조합한 'RGB 컬러 큐브' (6 * 6 * 6 = 216)
        * 232 ~ 255 (24개): 아주 어두운 회색부터 밝은 회색까지 표현하는 '무채색 그라데이션(Grayscale)'
      - 도트 아트(포켓몬, 마리오 등)를 구현할 때 고유 번호만 매핑하면 되므로 가장 널리 쓰임.

   D. 24-bit Color (True Color - 16,777,216가지 색상)
      - 원리: 현대 그래픽 시스템과 동일하게 Red, Green, Blue에 각각 1바이트(8비트)씩 통째로 할당함.
      - 수식: 2^24 = 2^8 * 2^8 * 2^8 = 256 * 256 * 256 = 16,777,216가지 조합
      - 특징: 인간의 눈으로 구별할 수 있는 거의 모든 색상을 표현 가능하여 '트루 컬러'라고 부름.
      - 게임 내에서 부드러운 배경 그라데이션, 시간 변화(노을, 밤) 등을 연출할 때 극적인 효과를 냄.

3. 터미널 제어 문법 요약
   - 글자색(Foreground) 변경: \033[38;5;[번호]m (8-bit) 또는 \033[38;2;[R];[G];[B]m (24-bit)
   - 배경색(Background) 변경: \033[48;5;[번호]m (8-bit) 또는 \033[48;2;[R];[G];[B]m (24-bit)
================================================================================
*/

// 3-bit 색상 출력 함수 (8색)
// 3비트는 2의 3승 = 8가지 조합을 가짐. (Red, Green, Blue 채널의 On/Off 제어)
// 문법: \033[[30~37]m -> 30:Black, 31:Red, 32:Green, 33:Yellow, 34:Blue, 35:Magenta, 36:Cyan, 37:White
void show_3bit_color(void) 
{
    printf("--- [1] 3-bit Color Demo (8 Colors: 2^3 = 8) ---\n");
    printf("원리: R, G, B 각각 1비트씩 On/Off 제어\n\n");

    printf("\033[30m[30m Black\033[0m   ");
    printf("\033[31m[31m Red\033[0m   ");
    printf("\033[32m[32m Green\033[0m ");
    printf("\033[33m[33m Yellow\033[0m\n");
    printf("\033[34m[34m Blue\033[0m  ");
    printf("\033[35m[35m Purple\033[0m ");
    printf("\033[36m[36m Cyan\033[0m  ");
    printf("\033[37m[37m White\033[0m\n\n");
}

// 4-bit 색상 출력 함수 (16색)
// 4비트는 2의 4승 = 16가지 조합을 가짐. (3비트의 R,G,B + 1비트의 밝기/명도(Intensity) 제어)
// 문법: 기존 번호 앞에 '1;'을 붙이면 밝은 색상 레벨로 격상됨.
void show_4bit_color(void) 
{
    printf("--- [2] 4-bit Color Demo (16 Colors: 2^4 = 16) ---\n");
    printf("원리: 3-bit(R,G,B) + 1-bit(명도/Bright 제어)\n\n");

    // 일반 3비트 색상과 4비트 밝은 색상 비교
    printf("일반 색상(어두움): ");
    printf("\033[31mRed \033[0m");
    printf("\033[32mGreen \033[0m");
    printf("\033[33mYellow \033[0m");
    printf("\033[34mBlue \033[0m\n");

    printf("밝은 색상(고명도): ");
    printf("\033[1;31mBright Red \033[0m");
    printf("\033[1;32mBright Green \033[0m");
    printf("\033[1;33mBright Yellow \033[0m");
    printf("\033[1;34mBright Blue \033[0m\n\n");
}

// 8-bit 색상 출력 함수 (256색)
// 8비트는 2의 8승 = 256가지 조합을 가짐. (1바이트 통째로 하나의 색상 테이블 인덱스로 매핑)
// 문법: \033[38;5;[0-255]m (글자색) 또는 \033[48;5;[0-255]m (배경색)
// 게임 학과/동아리에서 도트 캐릭터 데이터 만들 때 숫자로 1:1 매핑하기 가장 직관적임.
void show_8bit_color(void) 
{
    printf("--- [3] 8-bit Color Demo (256 Colors: 2^8 = 256) ---\n");
    printf("원리: 1바이트 인덱스 매핑 (0~15 기본색, 16~231 컬러큐브, 232~255 그레이스케일)\n\n");

    // 16번부터 231번까지의 RGB 컬러 큐브 영역 중 일부를 격자로 출력하여 시각화
    printf(">> RGB 컬러 큐브 영역 샘플 출력 (6x6x6 중 일부):\n");
    int i = 0;
    for (i = 16; i < 88; i++) 
    {
        printf("\033[48;5;%dm  \033[0m", i); // 배경색(48)을 채워 블록 모양으로 출력
        if ((i - 15) % 12 == 0) 
        {
            printf("\n");
        }
    }

    printf("\n>> 무채색 그라데이션 영역 (232~255):\n");
    for (i = 232; i <= 255; i++) {
        printf("\033[48;5;%dm  \033[0m", i);
    }
    printf("\n\n");
}

// 24-bit 색상 출력 함수 (True Color)
// 24비트는 2의 24승 = 16,777,216가지 조합을 가짐. (R 8비트, G 8비트, B 8비트 = 총 3바이트 데이터)
// 문법: \033[38;2;R;G;Bm (글자색) 또는 \033[48;2;R;G;Bm (배경색)
// 수학적 계산 없이 반복문 안에서 RGB 변수 값만 바꿔주면 스무스한 그라데이션 연출 가능.
void show_24bit_color(void) 
{
    printf("--- [4] 24-bit Color Demo (True Color: 2^24 = 16.7M) ---\n");
    printf("원리: R(8bit) + G(8bit) + B(8bit) 각 채널별 0~255 값을 직접 제어\n\n");

    printf(">> 빨간색에서 녹색으로 변하는 트루컬러 그라데이션 연출:\n");
    
    int i = 0;
    // R값을 줄이고 G값을 늘리면서 미세한 색상 변화 표현
    for (i = 0; i <= 255; i += 6) 
    {
        int r = 255 - i;
        int g = i;
        int b = 50; // 블루는 고정
        printf("\033[48;2;%d;%d;%dm \033[0m", r, g, b);
    }
    printf("\n\\n");
}

int main(void) 
{
    // 터미널 화면 청소 및 커서 최상단 이동
    printf("\033[2J\033[H");

    printf("====================================================\n");
    printf(" C언어 ANSI Escape Sequence 비트별 컬러 시스템 분석\n");
    printf("====================================================\n\n");

    // 순차적으로 모든 비트 단위 컬러 함수 호출
    show_3bit_color();
    show_4bit_color();
    show_8bit_color();
    show_24bit_color();

    printf("====================================================\n");
    printf("설명 완료. 리셋 코드가 작동하여 현재 텍스트는 기본색임.\n");

    return 0;
}