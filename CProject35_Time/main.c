/*
================================================================================
[C언어 초보자 전용 초정밀 강의자료: 표준 입출력 버퍼링 메커니즘]
================================================================================
1. 왜 화면이 깜빡이거나 늦게 나오는가? (입출력 버퍼의 탄생 배경)
   - `printf`를 호출할 때마다 컴퓨터가 모니터(하드웨어)에 매번 신호를 보내 글자를
     그리게 하면 시스템 연산 속도가 극도로 느려짐. 모니터를 구동하는 하드웨어적인
     비용이 CPU 연산 속도에 비해 수천 배 이상 무겁기 때문임.
   - 그래서 C언어는 중간에 '버퍼(Buffer)'라는 장바구니 임시 메모리를 두고, 출력할
     데이터물들을 여기에 차곡차곡 모아두었다가 한 번에 내보내는 방식을 취함.

2. setvbuf() 함수의 정체와 매개변수 파헤치기
   - 함수 원형: int setvbuf(FILE *stream, char *buffer, int mode, size_t size);

   * 매개변수 [1] FILE *stream
     - 제어하고자 하는 대상을 지정함.
     - `stdout`: 표준 출력 (우리가 흔히 쓰는 콘솔 화면). 텍스트 게임 제작 시 필수 타겟임.
     - `stdin`: 표준 입력 (키보드 버퍼 장바구니).

   * 매개변수 [2] char *buffer
     - 개발자가 직접 메모리를 할당해서 버퍼 공간으로 쓸 크기를 지정하는 포인터 변수임.
     - `NULL`을 넣으면: "내가 직접 배열 만들기 귀찮으니 C언어 표준 런타임 니가 내부적으로
       알아서 메모리 공간 할당해서 써라"라는 뜻임. 대개 특수한 목적이 없다면 `NULL`을 씀.

   * 매개변수 [3] int mode (가장 중요 ⭐)
     - 장바구니를 어떤 방식으로 운영하고 털어낼 것인지 방식을 강제 결정하는 옵션임.
     - `_IOFBF` (Full Buffering / 완전 버퍼링):
       지정한 버퍼 크기(`size`)가 100% 가득 찰 때까지 줄바꿈(\n)이 있든 말든 화면 출력을
       절대 안 하고 버티며 메모리에 홀딩시킴. 텍스트 게임 프레임 최적화의 핵심 모드임.
     - `_IOLBF` (Line Buffering / 행 버퍼링):
       글자를 모으다가 줄바꿈 문자(`\n`)를 만나는 순간 모니터로 즉시 던짐. 일반 콘솔의 기본값.
     - `_IONBF` (No Buffering / 버퍼링 없음):
       장바구니를 완전히 없앰. `printf` 호출하자마자 모니터로 즉시 물리 신호를 쏨. 속도 제일 느림.

   * 매개변수 [4] size_t size
     - 장바구니의 총 크기를 바이트 단위로 지정함 (예: `10240`은 약 10KB 크기 데이터 축적 공간).

3. fflush(stdout); 를 반드시 세트로 써야 하는 이유
   - 게임 루프 안에서 `_IOFBF`(완전 버퍼링) 모드를 가동하면 줄바꿈(`\n`)이 나와도 화면을
     새로 그리지 않고 버퍼에 데이터를 계속 모으기만 함. 자잘하게 화면을 쪼개 그리지 않기
     때문에, 콘솔 특유의 "지독한 화면 깜빡임(Flickering)"이 완벽하게 예방됨.
   - 하지만 버퍼가 완전히 꽉 차기 전에는 화면에 아무것도 안 나오므로 화면이 멈춰 보임.
   - 그래서 맵과 캐릭터들을 `printf`로 버퍼에 싹 다 그려놓은 직후(1프레임 렌더링이 완성된 시점)에
     `fflush(stdout);`를 수동으로 딱 호출해 줘야 함.
   - "장바구니 다 채웠으니 지금 당장 모니터 화면에 대고 강제로 전부 털어라!" 하고 수동으로
     명령을 내리는 것임. 이를 생략하면 게임 화면이 전혀 갱신되지 않고 멈추는 대참사가 발생함.
================================================================================
*/

#include <stdio.h>
#include <time.h>    // clock(), struct timespec, CLOCKS_PER_SEC 표준 내장
#include <windows.h>

int main(void) {
    // -------------------------------------------------------------------------
    // [강의 내용 실전 적용 1] 무버퍼링 모드 (_IONBF) 테스트
    // -------------------------------------------------------------------------
    // 버퍼링을 없애버렸기 때문에 \n이 없어도 글자 하나하나가 즉시 모니터로 물리적 출력됨.
    setvbuf(stdout, NULL, _IONBF, 0);

    printf("1. 무버퍼링 모드: 글자가 하나씩 실시간으로 툭툭 튀어나옴\n");
    for (int i = 0; i < 5; i++) {
        printf("★ ");

        // 0.5초 대기
        Sleep(500);
    }
    printf("\n\n");


    // -------------------------------------------------------------------------
    // [강의 내용 실전 적용 2] 완전 버퍼링 모드 (_IOFBF) - fflush가 없을 때의 대참사
    // -------------------------------------------------------------------------
    // 이제부터 10KB짜리 큰 장바구니를 가동함. 꽉 차기 전엔 절대 출력 안 함.
    setvbuf(stdout, NULL, _IOFBF, 10240);

    printf("2. 완전 버퍼링 모드 (fflush 없음): \n");
    printf("줄바꿈(\\n)을 해도 화면에 안 나옴. 루프가 다 끝나야 한 번에 터질 거임.\n");

    for (int i = 0; i < 5; i++) {
        printf("Loading... [%d/5]\n", i + 1);
        // 분명 printf를 실행했고 개행(\n)도 넣었지만, 화면엔 아무것도 안 뜸.
        // 데이터가 모조리 10KB 장바구니 속에 완전히 갇혀있기 때문임.

        // 0.5초 대기
        Sleep(500);
    }
    // 이 시점까지 콘솔창은 먹통처럼 보임.
    printf("\n\n");


    // -------------------------------------------------------------------------
    // [강의 내용 실전 적용 3] 완전 버퍼링 모드 (_IOFBF) + fflush(stdout) 수동 제어
    // -------------------------------------------------------------------------
    printf("3. 완전 버퍼링 모드 (fflush 수동 제어): \n");
    printf("장바구니에 담아뒀다가 fflush를 만나는 순간 화면에 즉시 방출!\n");

    for (int i = 0; i < 5; i++) {
        printf("게임 프레임 그리는 중... (데이터 누적 %d)\n", i + 1);

        // 이 명령어 덕분에 버퍼가 가득 차지 않았어도 강제로 화면에 그림이 찍힘!
        // 게임 루프 마지막에 이것을 배치하면 깜빡임 없이 부드럽게 화면이 갱신됨.
        fflush(stdout);

        // 0.5초 대기
        Sleep(500);
    }
    printf("\n");

    return 0;
}