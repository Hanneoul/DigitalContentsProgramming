/*
 * [배경지식 요약]
 * 1. ANSI 색상 구조: \033[ (시작) + 코드번호 + m (끝)
 * 예: \033[31m -> 이후 출력되는 글자는 빨간색이 됨.
 * 2. 색상 초기화 (\033[0m): 색상을 지정하면 그 뒤에 오는 모든 글자에 영향을 미침.
 * 원래대로 돌리려면 반드시 Reset 코드를 써야 함.
 * 3. 코드 번호 규칙:
 * - 글자색(Foreground): 30 ~ 37 (기본 8색), 90 ~ 97 (밝은 8색)
 * - 배경색(Background): 40 ~ 47 (기본 8색), 100 ~ 107 (밝은 8색)
 * 4. 색상 정보 주석:
 * - 0: Reset (초기화)   - 1: Bold (굵게)
 * - 31: Red, 32: Green, 33: Yellow, 34: Blue, 35: Magenta, 36: Cyan, 37: White
 */

#include <stdio.h>

int main()
{
    // [1] 글자색 바꾸기 (31번: 빨간색)
    printf("\033[31m이 글자는 빨간색입니다.\033[0m\n");

    // [2] 배경색 바꾸기 (44번: 파란색 배경)
    printf("\033[44m이 글자는 배경이 파란색입니다.\033[0m\n");

    // [3] 글자색 + 배경색 + 굵게 조합하기 (1번: Bold, 33번: 노란글씨, 41번: 빨간배경)
    // 세미콜론(;)으로 구분하여 여러 효과를 동시에 줄 수 있음
    printf("\033[1;33;41m경고: 아주 중요한 메시지!\033[0m\n\n");

    // [4] 색상표 예시 출력
    printf("--- 간단 색상표 ---\n");
    for (int i = 30; i <= 37; i++)
    {
        // %d 위치에 색상 번호를 넣어 반복 출력함
        printf("\033[%dm Color %d \033[0m ", i, i);
    }
    printf("\n");

    return 0;
}