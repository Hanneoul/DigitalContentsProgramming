/*
 * [배경지식 요약]
 * 1. #include <stdio.h> : 컴퓨터에게 "입출력(Standard Input/Output) 도구함을 가져와"라고 시키는 것임.
 * 2. main() : 프로그램의 '시작점'임. 컴퓨터는 이 안의 내용을 위에서 아래로 한 줄씩 실행함.
 * 3. 변수 선언(char c) : 데이터를 담을 빈 상자를 만드는 것임. 'char'는 문자(Character) 한 개를 담겠다는 뜻임.
 * 4. 아스키코드(ASCII) : 컴퓨터는 내부적으로 숫자만 이해함. 그래서 'A'는 65, 'B'는 66처럼 문자와 숫자를 1:1로 매칭해둔 약속임.
 * 5. 서식 지정자(%c, %d) : printf 안에서 "이 자리에 문자를 넣어라(%c)", "이 자리에 숫자를 넣어라(%d)"라고 지정하는 자리표시자임.
 */

#include <stdio.h> // 표준 입출력 라이브러리를 포함함 (printf, getchar 사용을 위해 필요)

int main() // 프로그램 실행의 본체인 메인 함수를 시작함
{
    char c; // 문자를 저장할 수 있는 'c'라는 이름의 상자(변수)를 메모리에 만듦

    c = getchar(); // 사용자가 키보드로 입력한 문자 하나를 읽어서 상자 'c'에 저장함

    // \n은 줄바꿈임. %c 위치에는 문자 형태로, %d 위치에는 숫자(아스키코드) 형태로 상자 'c'의 내용을 출력함
    printf("\n\n\n %c = %d", c, c);

    return 0; // 프로그램을 정상적으로 종료하고 운영체제에 알림
}