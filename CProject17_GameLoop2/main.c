/*
 * =========================================================================
 * [심화 학습: 실시간 입력 처리와 conio.h]
 * =========================================================================
 * 1. conio.h (Console Input/Output) 란?
 * - C 표준(ANSI C)은 아니지만, Windows 환경에서 콘솔 창의 입출력을 제어하기 위해
 *   제공되는 비표준 라이브러리. (Visual Studio 등에서 기본 제공)
 * - scanf()와 달리 '엔터'를 치지 않아도 즉시 입력을 처리하는 함수들이 포함됨.
 *
 * 2. _kbhit() 함수 (KeyBoard HIT) - "멈추지 않는 감시자"
 * - 역할: 지금 이 순간 키보드 버퍼에 '눌린 키'가 있는지 확인만 함.
 * - 반환값: 키가 눌려 있으면 참(0이 아닌 값), 아니면 거짓(0)을 반환.
 * - 중요성: 일반적인 입력 함수는 사용자가 키를 누를 때까지 프로그램 전체를 멈추지만(Blocking),
 * _kbhit()은 키가 눌렸든 안 눌렸든 즉시 다음 코드로 넘어가게 해줌(Non-blocking).
 *
 * 3. _getch() 함수 - "데이터 수집가"
 * - 역할: 키보드 버퍼에 있는 문자 하나를 읽어옴.
 * - _kbhit()과 짝을 이뤄 사용함. (kbhit으로 확인하고, getch로 가져오기)
 *
 * * 4. 게임 루프와의 관계 (Non-blocking 루프)
 * - [입력 확인(_kbhit)] -> (있으면) [입력 처리(_getch)] -> (없어도) [업데이트/렌더링 수행]
 * - 이 구조 덕분에 플레이어가 가만히 있어도 적이 움직이거나 시간이 흐르는 게임이 가능해짐.
 * =========================================================================
 */

 /*
  * =========================================================================
  * [게임 개발 실습: 2차원 좌표 이동과 I-U-R 구조]
  * =========================================================================
  * 1. 입력(Input): 지금 어떤 키가 눌렸는가?
  * - _kbhit()과 _getch()를 조합하여 '기다리지 않고' 입력값을 수집함.
  * 2. 업데이트(Update): 수집된 입력을 바탕으로 세상을 변화시킴.
  * - x, y 좌표의 덧셈/뺄셈 연산을 통해 캐릭터의 위치를 결정함.
  * - 화면 밖으로 나가지 않도록 '경계 검사(Boundary Check)'를 수행함.
  * 3. 렌더링(Render): 결정된 최종 좌표를 화면에 그림.
  * - y좌표만큼 줄바꿈(\n), x좌표만큼 공백( )을 출력하여 위치를 잡음.
  * =========================================================================
  */

#include <stdio.h>
#include <conio.h>
#include <Windows.h>
#include <stdbool.h>

int main()
{
    // --- [데이터 초기화] ---
    int x = 10, y = 5;      // 캐릭터의 초기 위치 (2차원 좌표)
    bool isRunning = true;  // 게임 루프 제어
    char inputKey = 0;      // 현재 프레임에서 눌린 키를 저장

    // --- [게임 루프 시작] ---
    while (isRunning)
    {
        // --- 1. 입력 (Input) ---
        // 키가 눌렸을 때만 inputKey에 저장, 아니면 0(무입력)으로 초기화
        if (_kbhit())
        {
            inputKey = _getch();
        }
        else
        {
            inputKey = 0;
        }

        // --- 2. 업데이트 (Update) ---
        // 입력을 분석하여 좌표(데이터)를 수정함
        // W(위), S(아래), A(왼쪽), D(오른쪽) 이동 로직
        if (inputKey == 'w' || inputKey == 'W') y--;
        else if (inputKey == 's' || inputKey == 'S') y++;
        else if (inputKey == 'a' || inputKey == 'A') x--;
        else if (inputKey == 'd' || inputKey == 'D') x++;
        else if (inputKey == 'q' || inputKey == 'Q') isRunning = false;

        // [경계 검사] 화면 밖으로 캐릭터가 나가는 것을 방지
        if (x < 0) x = 0;
        if (x > 30) x = 30; // 가로 한계선
        if (y < 0) y = 0;
        if (y > 15) y = 15; // 세로 한계선


        // --- 3. 렌더링 (Render) ---
        system("cls"); // 화면 지우기

        printf("=== 2D 이동 테스트 (WASD: 이동 / Q: 종료) ===\n");
        printf(" 현재 좌표 - X: %d, Y: %d\n", x, y);
        printf("---------------------------------------------\n");

        // Y좌표만큼 줄바꿈을 하여 아래로 내림
        for (int i = 0; i < y; i++)
        {
            printf("\n");
        }

        // X좌표만큼 공백을 출력하여 오른쪽으로 밀음
        for (int j = 0; j < x; j++)
        {
            printf(" ");
        }

        // 최종 캐릭터 출력
        printf("(*_*)\n");

        // CPU 부하 방지 및 속도 조절
        Sleep(10);
    }

    printf("\n게임을 안전하게 종료합니다.\n");

    return 0;
}