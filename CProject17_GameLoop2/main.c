/*
[ Game Loop 시작 ]
          |
          v
+-----------------------+
|  1. 입력 (Input)      | <--- 키보드, 마우스, 조이스틱 신호 수집
+-----------------------+
          |
          v
+-----------------------+
|  2. 업데이트 (Update) | <--- 캐릭터 이동, 충돌 체크, 점수 계산 (데이터 변경)
+-----------------------+
          |
          v
+-----------------------+
|  3. 렌더링 (Render)   | <--- 변경된 데이터를 화면에 그리기 (printf, 그래픽 출력)
+-----------------------+
          |
          v
 [ 종료 조건 검사? (ESC) ] --- 아니오 ---> (다시 입력 단계로 이동)
          |
         예
          |
          v
  [ Game Loop 종료 ]
*/

/*
 * =========================================================================
 * [학습 주제: 게임 개발의 심장, '게임 루프(Game Loop)']
 * =========================================================================
 * 1. 게임 루프란?
 * - 사용자의 입력이 없어도 멈추지 않고 실시간으로 돌아가는 무한 반복문.
 * - 일반 프로그램이 '대기(Wait)' 중심이라면, 게임은 '흐름(Flow)' 중심임.
 * * 2. 게임 루프의 3대 핵심 구조 (The Big Three)
 * 1) 입력(Input): 사용자가 무엇을 눌렀는지 확인 (키보드, 마우스 등)
 * 2) 업데이트(Update): 캐릭터 이동, 충돌, 점수 등 게임 내 세상의 수치를 계산
 * 3) 렌더링(Render): 계산된 수치를 바탕으로 화면을 새로 그림 (printf, Draw)
 * * 3. 왜 이렇게 짜야 하는가? (구조화의 필요성)
 * - 코드가 섞이면 나중에 복잡한 게임을 만들 때 수정이 불가능해짐.
 * - "듣고(Input), 생각하고(Update), 말하기(Render)"를 분리하는 것이 핵심.
 * * [텍스트 구조 다이어그램]
 * While(게임이 실행 중인가?) {
 * [입력] -> 키 입력을 변수에 저장
 * [처리] -> 변수값 계산 (x = x + 1 등)
 * [출력] -> 화면 지우기 후 새로운 위치에 출력
 * }
 * =========================================================================
 */

#include <stdio.h>
#include <conio.h>    // getch() 사용
#include <Windows.h>  // system("cls"), Sleep() 사용
#include <stdbool.h>

int main()
{
    // --- [준비 단계: 초기화] ---
    int x = 10;            // 캐릭터의 수평 좌표
    bool isRunning = true; // 루프 제어 변수
    char input = 0;        // 입력값 저장용

    // --- [게임 루프 시작] ---
    while (isRunning)
    {
        // --- 1. 렌더링 (Render) ---
        // 화면을 지우고 현재 데이터(x)를 기준으로 화면을 그림
        system("cls");
        printf("=== GAME LOOP TEST ===\n");
        printf("A: 왼쪽, D: 오른쪽, Q: 종료\n\n");

        for (int i = 0; i < x; i++) printf(" ");
        printf("O\n"); // 현재 x 위치에 캐릭터 출력

        // --- 2. 입력 (Input) ---
        // 사용자로부터 키를 입력받음
        input = _getch();

        // --- 3. 업데이트 (Update) ---
        // 입력받은 데이터에 따라 게임 세상을 변화시킴
        if (input == 'a' || input == 'A')
        {
            x--; // 왼쪽으로 1칸 이동
            // continue 사용 예: 이동 처리 후 아래 코드를 볼 필요 없이 바로 위로 점프
            if (x < 0) { x = 0; continue; }
        }
        else if (input == 'd' || input == 'D')
        {
            x++; // 오른쪽으로 1칸 이동
            if (x > 40) x = 40;
        }
        else if (input == 'q' || input == 'Q')
        {
            // 루프 탈출 조건 (break 사용)
            isRunning = false;
            break;
        }

        // [참고] break와 continue의 차이점
        // - break: "나 게임 끌래!" (루프 완전 종료)
        // - continue: "이번 차례는 여기서 끝내고 다음 화면 바로 그리자!" (루프 재시작)
    }

    printf("\n게임이 정상적으로 종료되었습니다.\n");

    return 0;
}

