/*
================================================================================
 [터미널 환경 설정 및 해상도 제어 가이드]
================================================================================

 1. 창 크기 조절 명령 (Window Resizing)
 -------------------------------------------------------------------------
 - 명령: \033[8;[행];[열]t
 - 예시: \033[8;25;80t -> 세로 25줄, 가로 80칸으로 창 크기를 변경함.
 - 주의: 일부 최신 터미널(Windows Terminal 등)은 사용자 설정을 존중하여 이 명령을
   무시할 수도 있으나, 구형 CMD나 특정 에뮬레이터에서는 아주 잘 작동함.

 2. 폰트와 해상도의 관계
 -------------------------------------------------------------------------
 - 코드로 폰트 크기를 직접 바꿀 수는 없지만, 창의 가로/세로 칸수를 고정함으로써
   "우리 게임은 40x25 픽셀 환경이다"라는 규격을 강제할 수 있음.

 3. 화면 지우기와 커서 숨기기 (필수 세팅)
 -------------------------------------------------------------------------
 - \033[2J : 화면 전체 지우기[cite: 1].
 - \033[?25l : 깜빡이는 커서 숨기기. 게임 화면에서 커서가 보이면 몰입감이 깨짐.
 - \033[?25h : 프로그램 종료 전 커서 다시 보이기 (매너!).

================================================================================
*/

#include <stdio.h>

// 우리가 정한 게임의 논리적 해상도 (Screen Space : 화면공간)
#define LOGICAL_WIDTH  48
#define LOGICAL_HEIGHT 27

// 실제 터미널 칸수 (가로는 픽셀당 2칸씩 차지하므로 80칸이 필요함)
#define TERMINAL_COLS  96 
#define TERMINAL_ROWS  27

void init_console() 
{
    // 1. 창 크기 조절 (세로 ROWS, 가로 COLS)[cite: 1]
    printf("\033[8;%d;%dt", TERMINAL_ROWS, TERMINAL_COLS);

    // 2. 화면 전체 지우기[cite: 1]
    printf("\033[2J");

    // 3. 커서 숨기기
    printf("\033[?25l");

    // 4. (선택사항) 창 제목 바꾸기 (윈도우 전용 OS 명령)
    system("title My Pixel Game"); 
}

void draw_pixel(int x, int y, int r, int g, int b) 
{
    // x가 범위를 벗어나지 않게 체크하는 루틴을 넣으면 더 안전함
    if (x < 0 || x >= LOGICAL_WIDTH || y < 0 || y >= LOGICAL_HEIGHT) return;

    printf("\033[%d;%dH", y + 1, (x * 2) + 1);
    printf("\033[48;2;%d;%d;%dm  \033[0m", r, g, b);
}

int main() 
{
    // 시작하자마자 환경 설정 함수 호출
    init_console();

    int x = 0, y = 0;

    // 배경 그리기
    for (y = 0; y < LOGICAL_HEIGHT; y++) 
    {
        for (x = 0; x < LOGICAL_WIDTH; x++) 
        {
            draw_pixel(x, y, 50, 50, 50);
        }
    }

    // 중앙에 점 하나 찍어보기
    draw_pixel(LOGICAL_WIDTH / 2, LOGICAL_HEIGHT / 2, 255, 0, 0);

    // 메시지 출력
    printf("\033[%d;1H", LOGICAL_HEIGHT + 1);
    printf("창 크기가 %dx%d(칸)으로 설정되었습니다.\n", TERMINAL_COLS, TERMINAL_ROWS);

    // 종료 대기
    getchar();

    // 종료 전 커서 다시 살려내기
    printf("\033[?25h");

    return 0;
}







