/*
=============================================================================
[강의 자료: 엔터 없이 바로 입력받는 getch() 완벽 이해하기]
=============================================================================

1. getch()란 무엇인가?
   - scanf()가 입력을 완료하기 위해 반드시 '엔터(Enter)'를 요구하는 반면,
     getch()는 키보드 자판을 "누르는 순간" 그 값을 즉시 읽어오는 함수임.
   - "Get Character"의 약자로, 문자 단 하나를 입력받는 데 특화되어 있음.
   - Windows 환경에서 제공하는 <conio.h> (Console Input/Output) 헤더가 필요함.

2. scanf()와 getch()의 결정적 차이점
   ┌─────────────────────────────┬──────────────────┐
   │ 특징              │ scanf("%d", &var);                  │ var = getch();                     │
   ├─────────────────────────────┼──────────────────┤
   │ 엔터 입력 필요성  │ 필수 (엔터를 쳐야 데이터 전달)      │ 불필요 (누르는 즉시 전달)          │
   │ 에코 (Echo) 효과  │ 입력한 숫자가 화면에 보임           │ 입력한 문자가 화면에 보이지 않음   │
   │ 변수 저장 방식    │ 주소값(&)을 인자로 넘겨줌           │ 함수의 반환값(Return)을 대입함     │
   └─────────────────────────────┴──────────────────┘

3. getch()의 리턴값과 주의점
   - 키보드로 숫자 '1'을 누르면, getch()는 정수 1이 아니라 문자 '1'(ASCII 코드 값 49)을 반환함.
   - 따라서 조건문에서 비교할 때 `case 1:`이 아니라 문자 형태인 `case '1':`로 처리해야 함.
   - 입력한 문자가 화면에 자동으로 출력되지 않기 때문에(No-Echo), 필요하다면 개발자가
     printf()를 통해 사용자가 무엇을 눌렀는지 화면에 다시 보여주어야 함.

4. MUD 게임 구조에서의 이점
   - 방향키나 메뉴 선택(1, 2, 3)을 할 때 엔터를 치지 않아도 되므로 게임의 템포가 빨라짐.
   - 숫자가 아닌 대형 문자열 입력에 의한 프로그램 먹통(무한 루프) 현상을 원천 차단할 수 있음.
=============================================================================
*/

#include <stdio.h>
#include <conio.h> // getch() 함수를 사용하기 위해 반드시 필요한 헤더

int main() 
{
    // [게임 상태 변수 선언]
    int current_room = 1;  // 현재 플레이어의 위치 (1: 어두운 방, 2: 서재, 3: 비밀 통로)
    int has_key = 0;       // 열쇠 획득 여부 (0: 없음, 1: 있음)
    char command;          // getch()를 통해 키보드 입력을 저장할 '문자형' 변수

    // [게임 시작 인트로]
    printf("==================================================\n");
    printf("        TEXT MUD: 의문의 방 탈출 게임 (getch 버전)    \n");
    printf("==================================================\n");
    printf("눈을 떠보니 사방이 막힌 낯선 방에 갇혀 있습니다.\n");
    printf("주변을 탐색하고 올바른 명령을 내려 이곳을 탈출하십시오.\n\n");

    // [게임 루프] 탈출할 때까지 무한히 반복됨
    while (1) {
        printf("\n--------------------------------------------------\n");

        // 1번 방: 어두운 방 (시작 지점)
        if (current_room == 1) {
            printf("[현재 위치: 어두운 방]\n");
            printf("낡은 침대와 굳게 닫힌 철문이 보입니다.\n");
            printf("무엇을 하시겠습니까?\n");
            printf("1. 침대 밑을 조사한다.\n");
            printf("2. 철문을 열고 나간다.\n");
            printf("3. 옆에 있는 서재로 이동한다.\n");
        }
        // 2번 방: 서재
        else if (current_room == 2) {
            printf("[현재 위치: 먼지 쌓인 서재]\n");
            printf("수많은 책과 거대한 책상이 놓여 있습니다.\n");
            printf("무엇을 하시겠습니까?\n");
            printf("1. 책상 서랍을 열어본다.\n");
            printf("2. 수상한 책을 잡아당겨 본다.\n");
            printf("3. 다시 원래 있던 방으로 돌아간다.\n");
        }
        // 3번 방: 비밀 통로
        else if (current_room == 3) {
            printf("[현재 위치: 비밀 통로]\n");
            printf("책장이 움직이며 나타난 숨겨진 출구입니다.\n");
            printf("탈출용 레버가 보입니다.\n");
            printf("무엇을 하시겠습니까?\n");
            printf("1. 탈출 레버를 당긴다.\n");
            printf("2. 다시 서재로 돌아간다.\n");
        }

        // [getch를 이용한 사용자 입력 처리]
        printf("명령어 번호 입력 (키보드 자판을 누르면 즉시 실행됨): ");

        /* [getch 상세 설명]
           - 주소값(&)을 넘기던 scanf와 달리, getch()는 눌린 키의 값을 직접 '반환'하므로 대입 연산자(=)를 사용함.
           - 사용자가 키를 누르는 즉시 화면에 아무것도 안 뜬 채 다음 코드로 넘어가므로,
             어떤 키를 눌렀는지 인지할 수 있도록 printf로 출력해주는 것이 좋음.
        */
        command = _getch();
        printf("%c\n", command); // 사용자가 누른 키를 화면에 강제로 보여줌 (에코 효과)
        printf("--------------------------------------------------\n\n");

        // [입력된 문자에 따른 게임 로직 분기]
        // ※ 주의: getch()로 받은 값은 문사이므로 숫자 1이 아니라 문자 '1'과 비교해야 함.
        if (current_room == 1) {
            switch (command) {
            case '1':
                if (has_key == 0) {
                    printf("[결과] 침대 밑 먼지 속에서 반짝이는 [철문 열쇠]를 발견했습니다!\n");
                    has_key = 1;
                }
                else {
                    printf("[결과] 침대 밑에는 더 이상 아무것도 없습니다.\n");
                }
                break;
            case '2':
                if (has_key == 1) {
                    printf("[결과] 딸깍... 열쇠가 맞습니다! 철문이 열리며 빛이 들어옵니다.\n");
                    printf("★ 축하합니다! 방을 무사히 탈출하셨습니다. (Normal Ending) ★\n");
                    return 0;
                }
                else {
                    printf("[결과] 문이 굳게 잠겨 있습니다. 열쇠가 필요한 것 같습니다.\n");
                }
                break;
            case '3':
                printf("[결과] 서재 안으로 걸어 들어갑니다.\n");
                current_room = 2;
                break;
            default:
                printf("[경고] 잘못된 입력입니다. 키보드의 1, 2, 3 중에서 누르십시오.\n");
                break;
            }
        }
        else if (current_room == 2) {
            switch (command) {
            case '1':
                printf("[결과] 서랍 안에는 텅 빈 종이 조각만 뒹굴고 있습니다.\n");
                break;
            case '2':
                printf("[결과] 쿠쿠쿵... 책장이 옆으로 밀려나며 벽에 [비밀 통로]가 나타났습니다!\n");
                current_room = 3;
                break;
            case '3':
                printf("[결과] 다시 어두운 방으로 돌아갑니다.\n");
                current_room = 1;
                break;
            default:
                printf("[경고] 잘못된 입력입니다. 키보드의 1, 2, 3 중에서 누르십시오.\n");
                break;
            }
        }
        else if (current_room == 3) {
            switch (command) {
            case '1':
                printf("[결과] 레버를 당기자 벽 전체가 열리며 외부와 연결된 비밀 통로가 열립니다.\n");
                printf("★ 대성공! 아무도 모르는 비밀 통로로 완벽하게 탈출했습니다! (True Ending) ★\n");
                return 0;
            case '2':
                printf("[결과] 다시 먼지 쌓인 서재로 나갑니다.\n");
                current_room = 2;
                break;
            default:
                printf("[경고] 잘못된 입력입니다. 키보드의 1, 2 중에서 누르십시오.\n");
                break;
            }
        }
    }

    return 0;
}